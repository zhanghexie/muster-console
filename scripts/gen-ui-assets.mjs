#!/usr/bin/env node
/** Bundle the production runtime; prototypes are consumers, never the implementation source. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { buildSync, transformSync } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const runtimeDir = path.join(root, 'src/main/uiRuntime');
const require = createRequire(import.meta.url);
const d3Dir = path.resolve(path.dirname(require.resolve('d3')), '..');
const d3 = '/* ' + fs.readFileSync(path.join(d3Dir, 'LICENSE'), 'utf8') + ' */\n' + fs.readFileSync(path.join(d3Dir, 'dist/d3.min.js'), 'utf8');
const threeDir = path.resolve(path.dirname(require.resolve('three')), '..');
const threeVersion = JSON.parse(fs.readFileSync(path.join(threeDir, 'package.json'), 'utf8')).version;
const three = '/* Three.js ' + threeVersion + '\n' + fs.readFileSync(path.join(threeDir, 'LICENSE'), 'utf8') + ' */\n' +
  buildSync({ entryPoints: [path.join(runtimeDir, 'three.js')], bundle: true, write: false,
    format: 'iife', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none' }).outputFiles[0].text;
const pele = fs.readFileSync(require.resolve('pele/global'), 'utf8');
const read = name => fs.readFileSync(path.join(runtimeDir, name), 'utf8');
const js = names => transformSync(names.map(read).join('\n'), { loader: 'js', minify: true, target: 'es2022', legalComments: 'none' }).code;
const css = transformSync(read('styles.css'), { loader: 'css', minify: true }).code;
const shared = d3 + '\n' + three + '\n' + js(['bridge.js', 'expressions.js', 'components.js', 'data-components.js', 'advanced-components.js']);
const mermaid = pele + '\n' + js(['mermaid.js']);
const out = `/* eslint-disable */
/** Generated by scripts/gen-ui-assets.mjs from src/main/uiRuntime, pinned D3 7.9.0 (ISC), Three.js ${threeVersion} (MIT), and Pele (MIT).
 * Regenerate after runtime/skill changes; --check verifies without writing. */
export const UI_CONTRACT_CSS: string = ${JSON.stringify(css)};
export const UI_SHARED_RUNTIME_JS: string = ${JSON.stringify(shared)};
export const UI_MERMAID_RUNTIME_JS: string = ${JSON.stringify(mermaid)};
`;
const destination = path.join(root, 'src/main/uiAssets.ts');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== out) { console.error('uiAssets.ts 已过期，请重新生成'); process.exitCode = 1; }
  else console.log('ui assets are current');
} else {
  fs.writeFileSync(destination, out);
  console.log(`ui assets generated: shared ${shared.length}, css ${css.length}`);
}
