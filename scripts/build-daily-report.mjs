import fs from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const daily = path.join(root, 'resources/extensions/daily-report');
const [base, stylesheet] = await Promise.all([
  fs.readFile(path.join(root, 'src/renderer/src/styles/base.css'), 'utf8'),
  fs.readFile(path.join(daily, 'client/styles.css'), 'utf8'),
]);
const motionTokens = [...base.matchAll(/  --(?:dur|ease)-[\w-]+:[^;]+;/g)].map(match => match[0]).join('\n');
await fs.writeFile(path.join(daily, 'ui/panel.css'), `/* Generated by build-daily-report.mjs */\n:root {\n${motionTokens}\n}\n${stylesheet}`);
