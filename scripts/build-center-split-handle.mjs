import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { createServer } from 'node:http';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await fs.readFile(path.join(root, 'src/renderer/src/styles/base.css'), 'utf8');
const tokens = new Map();
for (const [, name, value] of source.matchAll(/(--(?:dur|ease)-[\w-]+)\s*:\s*([^;]+);/g)) {
  if (!tokens.has(name)) tokens.set(name, value.trim());
}
const motion = `#split-handle-prototype { ${[...tokens].map(([name,value]) => `${name}: ${value};`).join(' ')} }`;
const css = await fs.readFile(path.join(root, 'docs/prototypes/center-split-handle/center-split-handle.css'), 'utf8');
const entry = `
import React, { useEffect, useRef, useState } from 'react';
import { createRoot } from 'react-dom/client';
import { SplitHandlePrototype } from './docs/prototypes/center-split-handle/center-split-handle';
const compatibleState = snapshot => {
  const state = snapshot?.privateContent?.layout;
  if (!state || !Array.isArray(state.panes) || state.panes.length < 1 || state.panes.length > 2 ||
      !state.panes.every(id => id === 'a' || id === 'b') || new Set(state.panes).size !== state.panes.length ||
      !['row', 'col'].includes(state.direction) || !Number.isFinite(state.ratio) ||
      state.ratio < 0.25 || state.ratio > 0.75 || !state.panes.includes(state.focused)) return undefined;
  return { panes: [...state.panes], direction: state.direction, ratio: state.ratio, focused: state.focused };
};
function Preview() {
  const [restored, setRestored] = useState(() => ({ layout: compatibleState(window.openai?.widgetState), revision: 0 }));
  const current = useRef(restored.layout);
  useEffect(() => {
    const restore = event => {
      const layout = compatibleState(event.detail?.globals?.widgetState);
      if (!layout || JSON.stringify(layout) === JSON.stringify(current.current)) return;
      current.current = layout;
      setRestored(previous => ({ layout, revision: previous.revision + 1 }));
    };
    window.addEventListener('openai:set_globals', restore);
    return () => window.removeEventListener('openai:set_globals', restore);
  }, []);
  const remember = layout => {
    current.current = layout;
    if (!window.openai?.setWidgetState) return;
    const names = { a: '整理分屏布局', b: '打磨拖拽交互' };
    window.openai.setWidgetState({
      modelContent: { layout: layout.panes.length === 1 ? 'single' : layout.direction, panes: layout.panes.map(id => names[id]), ratio: layout.ratio },
      privateContent: { layout },
    }).catch(() => {});
  };
  return <SplitHandlePrototype key={restored.revision} initialState={restored.layout} onStateChange={remember}/>;
}
createRoot(document.getElementById('split-handle-mount')).render(<Preview/>);
requestAnimationFrame(() => {
  const element = document.getElementById('split-handle-prototype');
  if (!element || !globalThis.Tweak) return;
  const state = { width: 160, alpha: 0.8, blur: 12 };
  const render = () => {
    element.style.setProperty('--shp-halo-width', state.width + 'px');
    element.style.setProperty('--shp-halo-alpha', String(state.alpha));
    element.style.setProperty('--shp-drag-blur', state.blur + 'px');
  };
  const tweak = new Tweak({ container: element, onChange: render });
  tweak.addSlider(state, 'width', { label: '渐隐背景范围', min: 80, max: 240, step: 8, unit: 'px', reference: '--shp-halo-width' });
  tweak.addSlider(state, 'alpha', { label: '渐隐背景强度', min: 0.2, max: 1, step: 0.05, reference: '--shp-halo-alpha' });
  tweak.addSlider(state, 'blur', { label: '拖动时模糊强度', min: 4, max: 24, step: 1, unit: 'px', reference: '--shp-drag-blur' });
});
`;
const compiled = await build({
  absWorkingDir: root,
  stdin: { contents: entry, resolveDir: root, loader: 'tsx' },
  bundle: true, write: false, minify: true, format: 'iife', jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
});
const script = compiled.outputFiles[0].text.replaceAll('</script', '<\\/script');
const fragment = [
  '<!-- Generated by scripts/build-center-split-handle.mjs; interactive design prototype. -->',
  '<div id="split-handle-preview" class="viz-dotted-background">',
  '  <div id="split-handle-mount"></div>',
  '</div>',
  `<style>${motion}\n${css}</style>`,
  `<script>${script}</script>`,
  '',
].join('\n');
if (Buffer.byteLength(fragment) >= 1_000_000) throw new Error('Prototype exceeds the inline fragment budget');
const output = path.join(root, 'docs/prototypes/center-split-handle/center-split-handle.html');
await fs.writeFile(output, fragment);
const visualPath = process.argv.indexOf('--visual-copy');
if (visualPath >= 0) {
  const dest = process.argv[visualPath + 1];
  if (!dest || !path.isAbsolute(dest)) throw new Error('--visual-copy needs an absolute output path');
  await fs.mkdir(path.dirname(dest), { recursive: true });
  await fs.writeFile(dest, fragment);
}
console.log(`Built ${path.relative(root, output)} (${Buffer.byteLength(fragment)} bytes)`);
if (process.argv.includes('--serve')) {
  const server = createServer(async (req,res) => {
    if (req.url?.split('?')[0] !== '/') { res.writeHead(404); res.end(); return; }
    try {
      const latest = await fs.readFile(output, 'utf8');
      const html = `<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>分屏把手原型</title><style>:root{color-scheme:light dark}body{margin:0;padding:24px;background:light-dark(#f1f1f3,#18191b)}@media(max-width:480px){body{padding:12px}}</style>${latest}</html>`;
      res.setHeader('Content-Type', 'text/html; charset=utf-8');
      res.setHeader('Cache-Control', 'no-store');res.end(html);
    } catch {
      res.writeHead(503);res.end('Prototype is rebuilding; refresh shortly.');
    }
  });
  const portIndex = process.argv.indexOf('--port');
  const port = portIndex < 0 ? 0 : Number(process.argv[portIndex + 1]);
  if (!Number.isInteger(port) || port < 0 || port > 65535) throw new Error('--port needs a valid local port');
  await new Promise((resolve,reject) => { server.once('error',reject);server.listen(port, '127.0.0.1', resolve); });
  console.log(`Preview: http://127.0.0.1:${server.address().port}/`);
}
