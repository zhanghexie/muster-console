const ratio = (a,b) => {
  const l=c=>c.match(/[\d.]+/g).slice(0,3).map(v=>{const n=Number(v)/255;return n<=.04045?n/12.92:((n+.055)/1.055)**2.4;}).reduce((n,v,i)=>n+v*[.2126,.7152,.0722][i],0);
  return (Math.max(l(a),l(b))+.05)/(Math.min(l(a),l(b))+.05);
};
