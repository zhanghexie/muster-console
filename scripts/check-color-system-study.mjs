  check('focused filled composer has four matching borders and one persistent top highlight',Object.values(composer).slice(0,4).every(c=>c===composer.top)&&composer.shadow!=='none');
  await page.getByLabel('展开调度对话').click();
  await page.mouse.move(0,0);
  check('scheduler and worker have same badge primitive',await page.locator('.cs-workspace-entry .cs-pill').count()===3&&await page.locator('.cs-session-list .cs-pill').count()===4);
  const collapse=await page.getByLabel('收起调度对话').evaluate(el=>({border:getComputedStyle(el).borderTopWidth,shadow:getComputedStyle(el).boxShadow,bg:getComputedStyle(el).backgroundColor}));
