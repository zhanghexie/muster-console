  await page.getByLabel('青绿',{exact:true}).click();
  check('avatar remains independent of project accent',await page.locator('.cs-agent-mark').first().evaluate(el=>getComputedStyle(el).backgroundColor)===identity);
  await page.getByLabel('玫瑰',{exact:true}).click();
  await page.getByRole('tab',{name:'ui-kit',exact:true}).click();
  check('content tools end before resource panel',await page.locator('.cs-localbar').evaluate(el=>el.getBoundingClientRect().right<=document.querySelector('.cs-resources').getBoundingClientRect().left));
  const backgrounds=await resolvedSurfaces();
  check('dark selected tab and chrome have a visible layer gap',ratio(backgrounds.selected,backgrounds.strip)>=1.5&&ratio(backgrounds.canvas,backgrounds.strip)>=1.2);
  report.darkSurfaceRatios={toolContent:ratio(backgrounds.canvas,backgrounds.strip),selectedTool:ratio(backgrounds.selected,backgrounds.strip)};
  await screenshot('dark-rose-git'); report.screenshots.push('dark-rose-git');
  await page.getByRole('tab',{name:'设置页原型',exact:true}).click();
  await screenshot('dark-rose-browser'); report.screenshots.push('dark-rose-browser');
  await button('终端分屏').click();
  await page.locator('.cs-terminal-body').click();
  const surfaces=await page.locator('.cs-terminal').evaluate(el=>({terminal:getComputedStyle(el).backgroundColor,chat:getComputedStyle(document.querySelector('.cs-chat')).backgroundColor,outline:getComputedStyle(el).outlineStyle}));
  check('terminal and chat share final content background without active pane outline',surfaces.terminal===surfaces.chat&&surfaces.outline==='none');
