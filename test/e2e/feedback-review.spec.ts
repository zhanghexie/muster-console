/** Production feedback UI + IPC + service in an isolated Electron window; remote API is simulated. */
import { test, expect, _electron as electron } from '@playwright/test';
import { build } from 'esbuild';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

const repo = path.resolve(__dirname, '..', '..');
const nodeRequire = createRequire(__filename);
const electronExecutable = nodeRequire('electron') as string;

test('deduplicates anonymously and verifies an Issue only after the user submits on GitHub', async () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'ma-feedback-e2e-'));
  let application: Awaited<ReturnType<typeof electron.launch>> | undefined;
  try {
    const main = path.join(temp, 'main.cjs'), renderer = path.join(temp, 'renderer.js');
    await build({ entryPoints: [path.join(repo, 'test/fixtures/feedback-electron-main.ts')], outfile: main,
      bundle: true, platform: 'node', format: 'cjs', external: ['electron'], logLevel: 'silent' });
    await build({ entryPoints: [path.join(repo, 'test/fixtures/feedback-electron-renderer.tsx')], outfile: renderer,
      bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"', 'import.meta.env.DEV': 'false' }, logLevel: 'silent' });
    const styles = ['base', 'dialogs', 'chrome', 'feedback'].map(name => `<link rel="stylesheet" href="${pathToFileURL(path.join(repo, `src/renderer/src/styles/${name}.css`)).href}">`).join('');
    const html = path.join(temp, 'index.html');
    fs.writeFileSync(html, `<!doctype html><html><head>${styles}<link rel="stylesheet" href="./renderer.css"></head><body><div id="root"></div><script src="${pathToFileURL(renderer).href}"></script></body></html>`);
    fs.mkdirSync(path.join(temp, 'profile'));
    const env: NodeJS.ProcessEnv = { ...process.env, MUSTER_FEEDBACK_E2E_PROFILE: path.join(temp, 'profile'), MUSTER_FEEDBACK_E2E_HTML: html,
      MUSTER_FEEDBACK_E2E_PRELOAD: path.join(repo, 'test/fixtures/feedback-electron-preload.cjs') }; delete env.ELECTRON_RUN_AS_NODE;
    application = await electron.launch({ executablePath: electronExecutable, args: [main], env: env as Record<string, string>, timeout: 30_000 });
    const page = await application.firstWindow();
    await page.getByRole('button', { name: 'Fixture: propose feedback' }).click();
    await page.getByRole('button', { name: '反馈审核（2 条待处理）' }).click();
    await expect(page.getByRole('textbox', { name: '标题' })).toHaveValue('切换工作区后列表滚动位置丢失');
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(0);
    await expect(page.getByRole('button', { name: '审核反馈' })).toBeEnabled();
    await expect(page.getByLabel('反馈令牌')).toHaveCount(0);
    const editor = page.getByRole('textbox', { name: '实际情况' });
    const detail = `用户补充：仍可复现。\n${'切换较多工作区时，列表总是回到顶部。'.repeat(35)}`;
    await editor.fill(`${await editor.inputValue()}\n\n${detail}`);
    await page.getByRole('button', { name: '保存草稿' }).click();
    await expect(page.getByText('等待 AI 查重')).toBeVisible();
    await page.evaluate(() => (window.api as any).fixture.assess());
    await expect(page.getByText('等待 AI 查重')).toHaveCount(0);
    await page.getByRole('button', { name: '审核反馈' }).click();
    await expect(page.getByLabel('提交前核对').getByRole('textbox', { name: '证据与不确定性' })).toHaveValue(/一次观察/);
    await expect(page.getByLabel('提交前核对').getByRole('textbox', { name: '实际情况' })).toHaveAttribute('readonly', '');
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(0);
    expect(await page.evaluate(() => (window.api as any).fixture.opened())).toHaveLength(0);
    await expect(page.getByText(/GitHub 只会预填标题/)).toBeVisible();
    await page.getByRole('button', { name: '复制正文并打开 GitHub' }).click();
    const panel = page.getByRole('dialog', { name: '反馈审核' });
    await expect(panel.getByRole('status')).toContainText('在 Write 页签粘贴');
    const [opened] = await page.evaluate(() => (window.api as any).fixture.opened());
    expect(opened).toMatch(/^https:\/\/github.com\/zhanghexie\/muster-console\/issues\/new\?/);
    expect(new URL(opened).searchParams.has('body')).toBe(false);
    const originalBody = await page.evaluate(() => (window.api as any).fixture.clipboardText());
    expect(originalBody).toContain(detail);
    expect(originalBody).toMatch(/<!-- muster-feedback:[\w-]+ -->/);
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(0);
    await page.getByRole('button', { name: '核对是否已提交' }).click();
    const tip = page.locator('.app-tip-region');
    await expect(tip).toContainText('还没有找到这条 Issue');
    await page.evaluate(() => (window.api as any).fixture.replaceClipboard('其他应用复制的内容'));
    await page.getByRole('button', { name: '复制 Issue 正文' }).press('Enter');
    await expect(tip).toContainText('Issue 正文已复制');
    const copiedBody = await page.evaluate(() => (window.api as any).fixture.clipboardText());
    expect(copiedBody).toBe(originalBody);
    await page.evaluate(body => (window.api as any).fixture.submitOnGitHub(body), copiedBody);
    await page.getByRole('button', { name: '核对是否已提交' }).click();
    await expect(page.getByRole('button', { name: '查看已发送反馈' })).toBeVisible();
    const issues = await page.evaluate(() => (window.api as any).fixture.issues());
    expect(issues[0].title).toBe('切换工作区后列表滚动位置丢失');
    expect(issues[0].body).toContain('一次观察');
    expect(issues[0].body).toBe(originalBody);
    await page.getByRole('button', { name: '删除反馈' }).click();
    const confirmSubmitted = page.getByRole('dialog', { name: '删除反馈？' });
    await expect(confirmSubmitted).toContainText('不会删除仓库中的 Issue');
    await confirmSubmitted.getByRole('button', { name: '删除', exact: true }).click();
    await expect(page.getByRole('button', { name: /切换工作区后列表滚动位置丢失/ })).toHaveCount(0);
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(1);
    await page.getByRole('button', { name: /退出后任务状态没有保存/ }).click();
    await page.getByRole('button', { name: '拒绝反馈' }).click();
    await page.getByRole('button', { name: '删除反馈' }).click();
    const confirmDraft = page.getByRole('dialog', { name: '删除反馈？' });
    await confirmDraft.getByRole('button', { name: '删除', exact: true }).click();
    await expect(page.getByText('暂无反馈')).toBeVisible();
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(1);
    await expect(page.getByRole('button', { name: /反馈审核（\d+ 条待处理）/ })).toHaveCount(0);
    await page.getByRole('dialog', { name: '反馈审核' }).getByRole('button', { name: '关闭', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '反馈审核' })).toHaveCount(0);
    await page.getByRole('button', { name: 'Fixture: open settings' }).click();
    await page.getByRole('button', { name: '反馈审核', exact: true }).click();
    await page.getByRole('button', { name: '手动添加反馈' }).click();
    await page.getByRole('textbox', { name: '标题' }).fill('手动添加的反馈');
    const feedbackType = page.getByRole('combobox', { name: '类型' });
    await feedbackType.selectOption('improvement');
    await page.getByRole('textbox', { name: '涉及功能' }).fill('会话列表');
    await page.getByRole('textbox', { name: '使用场景' }).fill('切换工作区');
    await page.getByRole('textbox', { name: '实际情况' }).fill('列表重新回到顶部。');
    await page.getByRole('textbox', { name: '期望' }).fill('希望能够保留当前阅读位置。');
    await page.getByRole('textbox', { name: '复现步骤或触发条件' }).fill('切换后再返回。');
    await expect(page.getByRole('textbox', { name: '影响' })).toHaveCount(0);
    await page.getByRole('textbox', { name: '证据与不确定性' }).fill('观察到一次。');
    await page.getByRole('textbox', { name: '建议' }).fill('保存列表滚动位置。');
    await page.getByRole('textbox', { name: '环境' }).fill('Windows 11');
    await page.getByRole('button', { name: '保存草稿' }).click();
    await expect(page.getByText('等待 AI 查重')).toBeVisible();
    await expect(page.getByRole('textbox', { name: '实际情况' })).toHaveValue('列表重新回到顶部。');
    await expect(page.getByRole('textbox', { name: '期望' })).toHaveValue('希望能够保留当前阅读位置。');
    await expect(page.getByRole('textbox', { name: '建议' })).toHaveValue('保存列表滚动位置。');
    await expect(page.getByRole('textbox', { name: '环境' })).toHaveValue('Muster Console test\nWindows 11');
    await expect(page.getByRole('button', { name: '反馈审核（1 条待处理）' })).toBeVisible();
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(1);
    await page.evaluate(() => (window.api as any).fixture.assess());
    await expect(page.getByText('等待 AI 查重')).toHaveCount(0);
    await page.getByRole('button', { name: '审核反馈' }).click();
    const manualReview = page.getByRole('region', { name: '提交前核对' });
    await expect(manualReview.getByRole('textbox', { name: '使用场景' })).toHaveValue('切换工作区');
    await expect(manualReview.getByRole('textbox', { name: '实际情况' })).toHaveValue('列表重新回到顶部。');
    await expect(manualReview.getByRole('textbox', { name: '建议' })).toHaveValue('保存列表滚动位置。');
    await expect(manualReview.getByRole('textbox', { name: '环境' })).toHaveValue('Muster Console test\nWindows 11');
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(1);
    await page.getByRole('button', { name: '在 GitHub 提交' }).click();
    await expect(page.getByRole('button', { name: '核对是否已提交' })).toBeVisible();
    const shortIssuePage = await page.evaluate(async () => (await (window.api as any).fixture.opened()).at(-1));
    expect(new URL(shortIssuePage).searchParams.get('body')).toContain('保存列表滚动位置。');
    expect(await page.evaluate(() => (window.api as any).fixture.clipboardText())).toBe(originalBody);
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(1);
    await page.evaluate(() => (window.api as any).fixture.submitOnGitHub());
    await page.getByRole('button', { name: '核对是否已提交' }).click();
    await expect(page.getByRole('button', { name: '查看已发送反馈' })).toBeVisible();
    const manualIssue = (await page.evaluate(() => (window.api as any).fixture.issues()))[1];
    expect(manualIssue.body).toContain('列表重新回到顶部。');
    expect(manualIssue.body).toContain('希望能够保留当前阅读位置。');
    expect(manualIssue.body).toContain('保存列表滚动位置。');
    expect(manualIssue.body).toContain('Muster Console test\nWindows 11');
    expect(manualIssue.body).not.toContain('影响：');
    await page.getByRole('button', { name: '手动添加反馈' }).click();
    await page.getByRole('textbox', { name: '标题' }).fill('只填写标题的建议');
    await expect(page.getByRole('button', { name: '保存草稿' })).toBeEnabled();
    await page.getByRole('button', { name: '保存草稿' }).click();
    await expect(page.getByText('等待 AI 查重')).toBeVisible();
    expect(await page.evaluate(() => (window.api as any).fixture.issues())).toHaveLength(2);
  } finally {
    await application?.close();
    if (path.dirname(temp) !== os.tmpdir() || !path.basename(temp).startsWith('ma-feedback-e2e-')) throw new Error('Unsafe test cleanup path');
    fs.rmSync(temp, { recursive: true, force: true });
  }
});
