import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {createSharedCompiler} from './helpers/shared-compile.mjs';
fs.mkdirSync(path.resolve('.tmp'),{recursive:true});
const temp=fs.mkdtempSync(path.resolve('.tmp/knowledge-activity-'));
let store,secondaryStore;
try{
 const compile=createSharedCompiler(process.cwd(),path.join(temp,'compiled'));
 const {KnowledgeStore}=await import(pathToFileURL(compile('main/memory/knowledgeStore.ts')));
 const {knowledgeActivity}=await import(pathToFileURL(compile('main/memory/knowledgeActivity.ts')));
 store=new KnowledgeStore(path.join(temp,'assets'));
 const day=86400000,now=new Date(2026,9,22,12,0,0,0).getTime(),midnight=new Date(now);midnight.setHours(0,0,0,0);
 const startOfToday=midnight.getTime();
 const record=store.submit({kind:'user_preference',summary:'回答使用中文',applicability:[]},{namespace:'profile',origin:'user',explicit:true,now,evidence:[{id:'e',source:'user',eventTime:now,verification:'user_confirmed'}]}).record;
 const append=(target,id,kind,at)=>target.db.prepare('INSERT INTO events(record_id,kind,at,detail) VALUES(?,?,?,?)').run(id,kind,at,'依据核对后自动保存');
 for(let i=0;i<220;i++)append(store,record.id,'auto_admitted',now);
 const activity=knowledgeActivity([store],now);
 assert.equal(activity.items.length,200);assert.equal(activity.kindCounts24h.auto_admitted,220,'counts must not be limited to visible feed');
 assert.equal(activity.todayActivations,1,'repeated activation events of the same record count once per local calendar day');
 assert.equal(activity.kindCounts24h.approval_queued,undefined,'automatic activity never creates a human approval badge');
 assert.equal(activity.kindCounts24h.profile_write,1);assert.equal(activity.kindCounts24h.direct_write,undefined);
 assert.equal(activity.kindCounts24h.promoted,undefined,'no invented automatic promotion');
 assert(activity.items.every(e=>e.entryRef===record.id));
 // The event ledger may outlive the current record; daily statistics use full event identities.
 for(let i=0;i<224;i++)append(store,randomUUID(),'auto_admitted',startOfToday+1);
 append(store,randomUUID(),'user_restored',startOfToday);
 append(store,randomUUID(),'auto_superseded_source',now);
 append(store,record.id,'user_restored',startOfToday+2);
 append(store,record.id,'auto_superseded_source',now-1000);
 append(store,randomUUID(),'auto_admitted',startOfToday-1);
 append(store,randomUUID(),'auto_admitted',now-2*day);
 append(store,randomUUID(),'auto_admitted',now-7*day-1);
 append(store,randomUUID(),'remembered',now);
 append(store,randomUUID(),'evidence_linked',now);
 for(const [index,kind] of ['auto_admitted','auto_superseded_source','user_restored'].entries())append(store,randomUUID(),kind,now+index+1);
 append(store,record.id,'remembered',now+4);
 secondaryStore=new KnowledgeStore(path.join(temp,'secondary'));
 append(secondaryStore,record.id,'user_restored',now);
 const full=knowledgeActivity([store,secondaryStore],now);
 assert.equal(full.items.length,200);
 assert.equal(full.todayActivations,227,'all distinct IDs, including midnight restoration and replacement, count beyond the 200-item feed');
 assert.ok(full.todayActivations>full.items.length);
 assert.equal(full.kindCounts24h.auto_admitted,450,'24h counts events, including yesterday evening and restoration, but no future rows');
 assert.equal(full.kindCounts7d.auto_admitted,451,'7d includes earlier actual events but excludes future and older-than-seven-days rows');
 assert.equal(full.kindCounts24h.profile_write,1,'a future explicit profile write cannot inflate rolling counts');
 assert.equal(full.kindCounts7d.profile_write,1);
 assert.equal(full.kindCounts24h.direct_write,1,'ordinary direct writes do not count as daily automatic activations');
 assert.equal(full.kindCounts24h.evidence_linked,1,'evidence links do not create a second activated record');
 assert.ok(full.items.every(event=>event.ts<=now),'future rows cannot occupy the visible feed either');
 assert.equal(knowledgeActivity([store,secondaryStore],startOfToday).todayActivations,1,'at local midnight only the exact-midnight restoration belongs to the new calendar day');
 assert.equal(knowledgeActivity([],now).todayActivations,0);
 console.log('knowledge-activity: full distinct calendar-day activations, restoration, future filtering and truthful rolling counts passed');
}finally{secondaryStore?.close();store?.close();fs.rmSync(temp,{recursive:true,force:true});}
