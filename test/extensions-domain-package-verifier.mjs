import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const compile = createSharedCompiler(repo, path.join(repo, '.tmp', 'extensions-package-verifier-compile'));
const { ExtensionRunningPackageVerifier } = await import(pathToFileURL(compile('main/extensions/extensionPackageVerifier.ts')));
const input = { scope: 'global', extensionId: 'demo' };
let fingerprint = 'package-extension:' + 'a'.repeat(64);
let discovers = 0;
let watchAvailable = true;
const watcher = new EventEmitter();
watcher.close = () => { watcher.closed = true; };
const layout = { discover: async () => {
  discovers += 1;
  await new Promise(resolve => setTimeout(resolve, 5));
  return { descriptor: { scope: 'global', extensionId: 'demo', directory: '/tmp/demo', copiedPerWorkspace: false }, manifest: { id: 'demo', name: 'Demo', scope: 'global', surface: { kind: 'sidebar', entry: 'ui/panel.html' } }, fingerprint, files: ['extension.json'] };
} };
const verifier = new ExtensionRunningPackageVerifier({ layout, watch: (_directory, listener) => { if (!watchAvailable) throw new Error('watch unavailable'); watcher.on('fs', listener); return watcher; } });
await verifier.verify(input);
assert.equal(discovers, 1);
await verifier.verify(input);
assert.equal(discovers, 1, 'clean cache must avoid rediscovery');
watcher.emit('fs', 'change', 'ui/panel.html');
const before = discovers;
const [one, two, three] = await Promise.all([verifier.verify(input), verifier.verify(input), verifier.verify(input)]);
assert.equal(discovers, before + 1, 'dirty concurrent verification must coalesce');
assert.equal(one.fingerprint, two.fingerprint);
fingerprint = 'package-extension:' + 'b'.repeat(64);
watcher.emit('fs', 'change', 'ui/panel.html');
assert.equal((await verifier.verify(input)).fingerprint, fingerprint);
const stable = discovers;
watcher.emit('fs', 'change', 'data/todos.json');
await verifier.verify(input);
assert.equal(discovers, stable, 'excluded data changes must not dirty the package');
watcher.emit('error', new Error('watch unavailable'));
watchAvailable = false;
fingerprint = 'package-extension:' + 'c'.repeat(64);
await verifier.verify(input);
await verifier.verify(input);
assert.equal(discovers, stable, 'watcher fallback must keep the clean cache');
verifier.markDirty(input);
assert.equal((await verifier.verify(input)).fingerprint, fingerprint);
assert.equal(discovers, stable + 1, 'a dirty fallback entry must revalidate once');
const seeded = new ExtensionRunningPackageVerifier({ layout, watch: () => new EventEmitter() });
seeded.seed({ descriptor: { scope: 'global', extensionId: 'demo', directory: '/tmp/demo', copiedPerWorkspace: false }, manifest: { id: 'demo', name: 'Demo', scope: 'global', surface: { kind: 'sidebar', entry: 'ui/panel.html' } }, fingerprint, files: ['extension.json'] });
await seeded.verify(input);
assert.equal(discovers, stable + 1, 'seeded cache must avoid initial discovery');
const saved = await seeded.verify(input);
const older = Promise.withResolvers();
const race = new ExtensionRunningPackageVerifier({ layout: { discover: () => older.promise }, watch: () => watcher });
race.seed(saved);
race.markDirty(input);
const dirty = race.verify(input);
const fresh = { ...saved, fingerprint: 'package-extension:' + 'd'.repeat(64) };
race.options.layout.discover = async () => fresh;
await race.verifyFresh(input);
older.resolve(saved);
await dirty;
assert.equal((await race.verify(input)).fingerprint, fresh.fingerprint, 'a late scan cannot overwrite the reloaded package');
race.close();
verifier.close();
assert.equal(watcher.closed, true);
console.log('extensions-package-verifier: ok');


