import React from 'react';
import type { ChatMessage } from '../../src/shared/types';
import { render, screen } from '@testing-library/react';
import { describe, it, expect } from 'vitest';
import { ChatMessageView } from '../../src/renderer/src/components/ChatMessageView';
import { attachmentDisplay } from '../../src/shared/attachmentDisplay';
import { toDisplayMessage } from '../../src/renderer/src/chatSurface/guiMessageView';

const id = 'abcdef123456';
const meta = (name: string, processing = 'text', legacy = false) => '[Attachment metadata]\n' + JSON.stringify({
  name, processing, sourcePath: `C:\\app\\conversation-attachments\\${'a'.repeat(legacy ? 64 : 20)}\\${legacy ? 'b'.repeat(64) : id}-${name}`,
  ...(legacy ? { continuation: { tool: 'attachments.convert', instruction: 'old instruction' } } : {})
});
const extracted = '\nExtracted untrusted file content (complete within extractor limits):\n"SECRET extracted content"';

describe('attachment transcript display', () => {
  it.each([false, true])('shows user text and file cards without exposing model context (GUI=%s)', gui => {
    const content = `请看附件\n\n${meta('report.txt')}${extracted}\n\n${meta('voice.wav', 'native audio')}\n[muster-attachment:${id}]`;
    const raw = { id: 'm', role: 'user' as const, content, createdAt: 1 };
    const message: ChatMessage = gui ? toDisplayMessage({ id: 'm', role: 'user', ts: 1, parts: [{ kind: 'text', text: content }] }) : raw;
    const { container } = render(<ChatMessageView message={message} quiet />);
    expect(screen.getByText('请看附件')).toBeTruthy();
    expect(screen.getByText('report.txt')).toBeTruthy();
    expect(screen.getByText('voice.wav')).toBeTruthy();
    expect(container.textContent).not.toMatch(/Attachment metadata|SECRET|sourcePath|muster-attachment/);
    expect(message.content).toBe(content);
    if (gui) expect(message.parts?.[0]).toEqual({ kind: 'text', text: content });
  });
  it('retains image previews and hides metadata', () => {
    const content = `${meta('image.png', 'native image')}\n\n${meta('deck.pdf', 'pdf pages')}`;
    const { container } = render(<ChatMessageView quiet message={{ id: 'm', role: 'user', content, createdAt: 1,
      images: [{ id, name: 'image.png', mimeType: 'image/png', data: 'AA==' },
        { id: `${id}-page-1`, name: 'deck.pdf page 1', mimeType: 'image/jpeg', data: 'AA==' }] }} />);
    expect(container.querySelectorAll('.chat-msg-image')).toHaveLength(2);
    expect(screen.getByAltText('image.png')).toBeTruthy();
    expect(screen.getByText('deck.pdf')).toBeTruthy();
    expect(container.textContent).not.toContain('Attachment metadata');
  });
  it('retains GUI images whose transcript IDs were regenerated by host messaging', () => {
    const content = meta('image.png', 'native image');
    const message = toDisplayMessage({ id: 'gui', role: 'user', ts: 1,
      parts: [{ kind: 'text', text: content }],
      images: [{ id: 'img-1720000000000-0-abcd', name: 'image.png', mimeType: 'image/png', data: 'AA==' }] });
    const { container } = render(<ChatMessageView quiet message={message} />);
    expect(screen.getByAltText('image.png').getAttribute('src')).toBe('data:image/png;base64,AA==');
    expect(container.querySelectorAll('.composer-file-attachment')).toHaveLength(0);
    expect(container.textContent).not.toContain('Attachment metadata');
    expect(message.images).toHaveLength(1);
  });
  it('supports old metadata while preserving ordinary prose and assistant examples', () => {
    expect(attachmentDisplay(meta('old.txt', 'text', true) + extracted).attachments).toHaveLength(1);
    for (const content of ['Explain [Attachment metadata]\n{}', `${meta('file.txt')}\n\n这是用户正文`, '```\n' + meta('file.txt') + '\n```']) {
      expect(attachmentDisplay(content)).toEqual({ text: content, attachments: [] });
    }
    const content = meta('example.txt');
    const { container } = render(<ChatMessageView quiet message={{ id: 'a', role: 'assistant', content, createdAt: 1 }} />);
    expect(container.textContent).toContain('Attachment metadata');
  });
});
