import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'resume-wait-service-'));
let log, store;
try {
  const compile = createSharedCompiler(process.cwd(), path.join(tmp, 'compiled'));
  const load = p => import(pathToFileURL(compile(p)).href);
  const { EventLog } = await load('main/awareness/eventLog.ts');
  const { ResumeWaitStore } = await load('main/resumeWait/store.ts');
  const { ResumeWaitService } = await load('main/resumeWait/service.ts');
  const dir = path.join(tmp, 'data'); log = new EventLog(dir); store = new ResumeWaitStore(dir);
  let now = Date.parse('2026-11-02T12:00:00Z'), busy = true;
  const delivered = [], alerts = [];
  const env = { now: () => now, isBusy: () => busy,
    async deliver(wait, content, _deliveryId, batch) { delivered.push({ wait, content, batch }); return busy && wait.priority === 'normal'
      ? { status: 'queued', reason: 'boundary' } : { status: 'confirmed' }; },
    alert(wait, reason) { alerts.push({ id: wait.id, reason }); } };
  const service = new ResumeWaitService(store, env);
  const arm = (condition, more = {}) => service.arm('worker', 'ws', { condition, note: '原文\n  下一步', ...more });
  env.desktopEpoch = owner => owner === 'worker' ? { epoch: 'trusted-epoch-A', generation: 3 } : null;
  const epochWait = service.arm('worker', 'ws', { condition: { kind: 'mail', from: 'never-epoch' }, note: 'epoch', desktopEpoch: 'model-claim' });
  assert.equal(epochWait.desktopEpoch, 'trusted-epoch-A', 'only host state can bind an epoch');
  env.desktopEpoch = () => ({ epoch: 'trusted-epoch-B', generation: 4 });
  assert.equal(store.get(epochWait.id).desktopEpoch, 'trusted-epoch-A', 'later approvals do not rewrite the arm-time epoch');
  env.desktopEpoch = () => { throw Error('injected epoch storage failure'); };
  const unknownEpoch = service.arm('worker', 'ws', { condition: { kind: 'mail', from: 'never-unknown' }, note: 'still deliver text' });
  assert.equal(unknownEpoch.desktopEpoch, null);
  assert.equal(unknownEpoch.desktopEpochUnknown, true, 'a failed identity read is not treated as no prior epoch');
  assert.equal(store.get(unknownEpoch.id).desktopEpochUnknown, true);
  delete env.desktopEpoch;
  const missingEpoch = arm({ kind: 'mail', from: 'never-missing-identity' });
  assert.equal(missingEpoch.desktopEpochUnknown, true, 'a missing host identity provider is unknown, not an explicit empty epoch');
  env.desktopEpoch = () => undefined;
  const invalidEpoch = arm({ kind: 'mail', from: 'never-invalid-identity' });
  assert.equal(invalidEpoch.desktopEpochUnknown, true, 'undefined is not an explicit empty epoch');
  env.desktopEpoch = () => null;
  const emptyEpoch = arm({ kind: 'mail', from: 'never-empty-identity' });
  assert.equal(emptyEpoch.desktopEpochUnknown, false, 'a working provider can explicitly report no epoch');
  const withoutCapabilities = arm({ kind: 'mail', from: 'never-capability' });
  assert.equal(store.get(withoutCapabilities.id).state, 'armed', 'arming depends on bound identity and valid arguments, not optional native preemption capabilities');
  assert.throws(() => service.arm('worker', 'ws', { condition: { kind: 'mail' }, note: 'x'.repeat(2001) }), /2000/);
  const unicode = service.arm('worker', 'ws', { condition: { kind: 'mail', from: 'never' }, note: '😀'.repeat(2000) });
  assert.equal(unicode.note, '😀'.repeat(2000), 'Unicode code points agree with the exposed schema');
  const event = arm({ kind: 'event', source: 'gitlab', types: ['issue'], scope: '6528' });
  log.append({ source: 'gitlab', type: 'issue', scope: '6528', workspaceId: 'other', receivedAt: now, summary: 'other', payload: '{}' });
  service.events(log);
  assert.equal(store.get(event.id).state, 'armed', 'workspace isolation applies to events');
  log.append({ source: 'gitlab', deliveryId: 'delivery-1', type: 'issue', scope: '6528', workspaceId: 'ws', receivedAt: now, summary: 'issue', payload: '{"title":"untrusted"}' });
  service.events(log); service.events(log);
  await service.tick();
  assert.equal(store.get(event.id).state, 'ready', 'normal delivery stays queued while busy');
  for (let i = 0; i < 5; i++) { now += 1000; await service.tick(); }
  assert.equal(store.get(event.id).attempts, 1, 'busy boundary waiting does not create repeated delivery attempts');
  assert.match(delivered[0].content, /原文\n  下一步/);
  assert.match(delivered[0].content, new RegExp(`resumeRecordId: ${event.id}；fireInstanceId: fire-`));
  assert.match(delivered[0].content, /untrusted/);
  busy = false; now += 1001; await service.tick();
  assert.equal(store.get(event.id).state, 'consumed');
  const mail = arm({ kind: 'mail', from: 'child', replyTo: 'ask-1' }, { priority: 'preempt' });
  service.mail('ws', { id: 'mail-1', to: 'worker', from: 'child', replyTo: 'other', text: 'reply', ts: now });
  assert.equal(store.get(mail.id).state, 'armed');
  service.mail('ws', { id: 'mail-2', to: 'worker', from: 'child', meta: { replyAskId: 'ask-1' }, text: 'reply', ts: now });
  busy = true; await service.tick();
  assert.equal(store.get(mail.id).state, 'consumed', 'preempt is submitted while busy');
  // Replaces issue #4's 30.5-second real wait: time advances while the
  // agent is free to work, then the same waiting session receives the mail.
  const late = arm({ kind: 'mail', from: 'child', replyTo: 'ask-late' });
  now += 30500;
  service.mail('ws', { id: 'mail-late', to: 'worker', from: 'child', meta: { replyAskId: 'ask-late' }, text: 'late reply', ts: now });
  busy = false; await service.tick();
  assert.equal(store.get(late.id).state, 'consumed');
  assert.match(delivered.at(-1).content, /原文\n  下一步/);
  const state = arm({ kind: 'session', sessionId: 'child', phase: 'needs_you' });
  service.session('child', 'idle', {});
  assert.equal(store.get(state.id).state, 'armed');
  service.session('child', 'needs_you', { busy: false });
  busy = false; await service.tick();
  assert.equal(store.get(state.id).state, 'consumed');
  const timed = arm({ kind: 'time', at: '2026-11-02T12:01:00Z' });
  const deadline = arm({ kind: 'mail' }, { deadlineMs: 3000 });
  now += 3000; await service.tick();
  assert.equal(store.get(deadline.id).triggerId, 'deadline');
  assert.match(delivered.at(-1).content, /续接-超时/);
  const beforeDeadline = arm({ kind: 'time', at: new Date(now + 2000).toISOString() }, { deadlineMs: 5000 });
  const afterDeadline = arm({ kind: 'time', at: new Date(now + 5000).toISOString() }, { deadlineMs: 2000 });
  const equalDeadline = arm({ kind: 'time', at: new Date(now + 2000).toISOString() }, { deadlineMs: 2000 });
  now += 6000; await service.tick();
  assert.match(store.get(beforeDeadline.id).triggerId, /^time:/, 'earlier planned time wins after a delayed scan');
  assert.equal(store.get(afterDeadline.id).triggerId, 'deadline', 'earlier deadline wins after a delayed scan');
  assert.match(store.get(equalDeadline.id).triggerId, /^time:/, 'time wins an equal deadline');
  now += 60000; await service.tick();
  assert.equal(store.get(timed.id).state, 'consumed');
  busy = true;
  const batchA = service.arm('worker', 'ws', { condition: { kind: 'time', at: '2026-11-02T12:00:00Z' }, note: 'first note' });
  const batchB = service.arm('worker', 'ws', { condition: { kind: 'time', at: '2026-11-02T12:00:00Z' }, note: 'second note' });
  const beforeBatch = delivered.length;
  await service.tick();
  assert.equal(delivered.length, beforeBatch + 1, 'normal waits for the same owner share one queued delivery');
  assert.deepEqual(delivered.at(-1).batch.map(item => item.id).sort(), [batchA.id, batchB.id].sort(), 'host receives every wait identity in the batch');
  assert.match(delivered.at(-1).content, /first note/);
  assert.match(delivered.at(-1).content, /second note/);
  busy = false; env.deliver = async (wait, content) => { delivered.push({ wait, content }); return { status: 'submitted' }; };
  await service.tick();
  assert.equal(store.get(batchA.id).state, 'delivering');
  const batchId = store.get(batchA.id).deliveryId;
  assert.equal(store.get(batchB.id).deliveryId, batchId);
  assert.equal(service.acknowledge('worker', batchId), true);
  assert.equal(store.get(batchA.id).state, 'consumed');
  assert.equal(store.get(batchB.id).state, 'consumed', 'one exact turn receipt settles every wait in that batch');
  env.deliver = async () => ({ status: 'submitted' });
  const receipt = arm({ kind: 'time', at: '2026-11-02T12:00:00Z' });
  await service.tick();
  assert.equal(store.get(receipt.id).state, 'delivering', 'queue admission is not a turn-start receipt');
  const receiptDelivery = store.get(receipt.id).deliveryId;
  assert.equal(service.acknowledge('other', receiptDelivery), false);
  assert.equal(service.acknowledge('worker', receiptDelivery), true);
  assert.equal(store.get(receipt.id).state, 'consumed');
  const missing = arm({ kind: 'time', at: '2026-11-02T12:00:00Z' });
  await service.tick();
  const firstDelivery = store.get(missing.id).deliveryId;
  const firstFire = store.get(missing.id).fireInstanceId;
  now += 30001; await service.tick();
  assert.equal(store.get(missing.id).state, 'uncertain');
  assert.ok(alerts.some(item => item.id === missing.id));
  now += 89999; await service.tick();
  assert.equal(store.get(missing.id).state, 'uncertain', 'uncertainty grace is observed');
  now += 1; await service.tick(); await service.tick();
  const retryDelivery = store.get(missing.id).deliveryId;
  assert.equal(store.get(missing.id).state, 'delivering');
  assert.notEqual(retryDelivery, firstDelivery, 'each submission has a distinct receipt identity');
  assert.equal(store.get(missing.id).fireInstanceId, firstFire, 'the logical trigger identity is stable across retries');
  assert.equal(service.acknowledge('worker', firstDelivery), true, 'a late receipt for the first attempt closes the logical wait');
  assert.equal(store.get(missing.id).state, 'consumed');
  assert.deepEqual(store.history(missing.id).map(item => item.status),
    ['attempted', 'uncertain', 'retry-due', 'redelivered', 'confirmed-late']);
  assert.equal(service.acknowledge('worker', retryDelivery), true, 'a second attempt receipt is audited after closure');
  assert.equal(service.acknowledge('worker', retryDelivery), false, 'the same receipt is recorded only once');
  assert.equal(store.history(missing.id).at(-1).status, 'confirmed-late');
  await service.tick();
  assert.equal(store.get(missing.id).attempts, 2, 'a late receipt prevents another attempt');
  let releaseFirst, callCount = 0;
  env.deliver = async () => {
    if (++callCount === 1) return new Promise(resolve => { releaseFirst = resolve; });
    return { status: 'submitted' };
  };
  const stalled = arm({ kind: 'time', at: '2026-11-02T12:00:00Z' });
  const firstTick = service.tick();
  assert.equal(typeof releaseFirst, 'function');
  const stalledDelivery = store.get(stalled.id).deliveryId;
  now += 30001; await service.tick(); now += 90000; await service.tick(); await service.tick();
  assert.equal(callCount, 2, 'a hung admission does not block the uncertainty retry');
  assert.equal(service.acknowledge('worker', stalledDelivery), true);
  releaseFirst({ status: 'submitted' }); await firstTick; await service.tick();
  assert.equal(callCount, 2, 'a late receipt also closes a wait whose first admission is still pending');
  env.deliver = async () => ({ status: 'submitted' });
  const expired = arm({ kind: 'mail' }, { deadlineMs: 1 });
  now += 8 * 24 * 60 * 60 * 1000; await service.tick();
  assert.equal(store.get(expired.id), undefined, 'expired records are removed only after notification');
  assert.ok(alerts.some(item => item.id === expired.id && /七天/.test(item.reason)));
  const failures = [];
  env.deliver = async wait => { failures.push(wait.failures); return { status: 'deferred', reason: 'definitely not submitted' }; };
  const retry = arm({ kind: 'time', at: '2026-11-02T12:00:00Z' });
  await service.tick(); now += 500; await service.tick(); now += 1500; await service.tick();
  assert.deepEqual(failures, [0, 1, 2], 'known non-submissions retry with bounded backoff and retain escalation count');
  assert.equal(store.get(retry.id).failures, 3);
} finally { store?.close(); log?.close(); fs.rmSync(tmp, { recursive: true, force: true, maxRetries: 3 }); }
console.log('resume-wait-service: ok');
