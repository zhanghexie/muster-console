import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-seat-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { DesktopInputSeat } = await import(pathToFileURL(compile('main/desktop/inputSeat.ts')));
  let now = 100, releases = 0;
  const seat = new DesktopInputSeat(async () => { releases++; }, 10, () => now);
  let enter, finish;
  const entered = new Promise(resolve => { enter = resolve; });
  const pending = new Promise(resolve => { finish = resolve; });
  let signal;
  const first = seat.run(async s => { signal = s; enter(); await pending; return 'should not succeed'; });
  await entered;
  const second = seat.run(async () => 'should not run');
  await seat.userTakeover();
  assert.equal(signal.aborted, true);
  assert.equal(releases, 1, 'keys must be released before the operation returns');
  finish();
  await assert.rejects(first, /interrupted by user/);
  await assert.rejects(second, /paused after user takeover/);
  assert.equal(releases, 2, 'operation cleanup releases again after stopping');
  await seat.resume();
  await assert.rejects(seat.run(async () => 1), /rate limit/);
  now += 10;
  assert.equal(await seat.run(async () => 2), 2);
  await assert.rejects(seat.run(async () => 3), /rate limit/);
  now += 10;
  await assert.rejects(seat.run(async () => { throw new Error('backend failed'); }), /backend failed/);
  assert.equal(releases, 4);
  const cancellation = new AbortController();
  let finishCancelled, enterCancelled;
  const cancelledStarted = new Promise(resolve => { enterCancelled = resolve; });
  const cancelledWait = new Promise(resolve => { finishCancelled = resolve; });
  now += 10;
  const cancelled = seat.run(async signal => { enterCancelled(signal); await cancelledWait; }, cancellation.signal);
  const cancelledSignal = await cancelledStarted;
  cancellation.abort(new Error('task cancelled'));
  assert.equal(cancelledSignal.aborted, true);
  finishCancelled();
  await assert.rejects(cancelled, /task cancelled/);
  assert.equal(releases, 5);
  const order = [];
  let finishSerial, enterSerial;
  const serialWait = new Promise(resolve => { finishSerial = resolve; });
  const serialStarted = new Promise(resolve => { enterSerial = resolve; });
  const serial = new DesktopInputSeat(async () => { order.push('release'); }, 0);
  const a = serial.run(async () => { order.push('a-start'); enterSerial(); await serialWait; order.push('a-end'); });
  await serialStarted;
  const b = serial.run(async () => { order.push('b-start'); });
  await Promise.resolve();
  assert.deepEqual(order, ['a-start']);
  finishSerial();
  await Promise.all([a, b]);
  assert.deepEqual(order, ['a-start', 'a-end', 'release', 'b-start', 'release']);
  const broken = new DesktopInputSeat(async () => { throw new Error('release failed'); }, 0);
  await assert.rejects(broken.userTakeover(), /release failed/);
  await assert.rejects(broken.resume(), /release failed/);
  await assert.rejects(broken.run(async () => 1), /paused/);
  const syncBroken = new DesktopInputSeat(() => { throw new Error('sync release failed'); }, 0);
  await assert.rejects(syncBroken.userTakeover(), /sync release failed/);
  await assert.rejects(syncBroken.resume(), /sync release failed/);
  await assert.rejects(syncBroken.run(async () => 1), /paused/);
  const cleanupBroken = new DesktopInputSeat(async () => { throw new Error('cleanup release failed'); }, 0);
  await assert.rejects(cleanupBroken.run(async () => 1), /cleanup release failed/);
  await assert.rejects(cleanupBroken.resume(), /cleanup release failed/);
  await assert.rejects(cleanupBroken.run(async () => 2), /paused/);
  console.log('desktop seat: serialization, takeover, release and rate limits passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
