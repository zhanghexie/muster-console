/** Host collision recording contract, independent of Electron and model runtimes. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require=createRequire(import.meta.url), ts=require('typescript'), Module=require('node:module');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const file=path.join(root,'src/main/turnChanges/collisions.ts');
const compiled=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText;
let syncs=0,persists=0;
const module=new Module(file);
module.require=name=>name==='../agentSession/host/base'?{syncEntry:()=>syncs++,persistEntry:()=>persists++}:name==='../../shared/i18n'?{t:(key,args={})=>key.replace(/\{\{(\w+)\}\}/g,(_,k)=>args[k]??'')}:require(name);
module._compile(compiled,file);
const {recordTurnFileCollision}=module.exports;
const a={owner:'gui:a',messageId:'ma',cwd:root,summary:{id:'sa',state:'collecting',files:[],warnings:[],concurrentEdits:[{path:'second.ts',otherOwner:'dispatch:ws',otherLabel:'dispatch:ws'}]}};
const b={owner:'dispatch:ws',messageId:'mb',cwd:root,summary:{id:'sb',state:'collecting',files:[],warnings:[],concurrentEdits:[{path:'second.ts',otherOwner:'gui:a',otherLabel:'gui:a'}]}};
const guiMessage={id:'ma',turnChanges:{...a.summary}}, dispatchMessage={id:'mb',turnChanges:{...b.summary}};
const notifications=[],events=[];
const guiEntry={messages:[guiMessage]},bucket={display:[dispatchMessage]};
const ctx={sessions:{get:()=>({name:'界面会话',workspaceId:'ws'})},config:{get:()=>({workspaces:[{id:'ws',name:'项目'}]})},agentSessions:{entries:new Map([['a',guiEntry]])},orchestrator:{buckets:new Map([['ws',bucket]]),emit:(...args)=>events.push(args),persistBucket:()=>persists++},notify:{push:input=>notifications.push(input)}};
recordTurnFileCollision(ctx,{file:path.join(root,'second.ts'),participants:[a,b]});
assert.deepEqual(notifications,[],'recording a collision must not send desktop notifications');
assert.equal(guiMessage.turnChanges.concurrentEdits[0].otherLabel,'项目 · 调度');
assert.equal(dispatchMessage.turnChanges.concurrentEdits[0].otherLabel,'界面会话');
assert.equal(syncs,1);assert.equal(persists,2);assert.equal(events[0][0],'agent:message');
guiEntry.messages=[];bucket.display=[];syncs=0;persists=0;events.length=0;
recordTurnFileCollision(ctx,{file:path.join(root,'third.ts'),participants:[a,b]});
assert.equal(syncs,0);assert.equal(persists,0);assert.equal(events.length,0,'no removed messages are resurrected');
assert.deepEqual(notifications,[]);
console.log('turn-changes-collisions: peer labels, both surfaces, silent recording and removed-message guard passed');
