import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'muster-store-routing-'));
try {
  const compile = createSharedCompiler(process.cwd(), temp);
  const electron = path.join(temp, 'node_modules', 'electron'); fs.mkdirSync(electron, { recursive: true });
  fs.writeFileSync(path.join(electron, 'package.json'), JSON.stringify({ name: 'electron', type: 'module', main: 'index.mjs' }));
  fs.writeFileSync(path.join(electron, 'index.mjs'), 'export const app={getPath:()=>globalThis.__storagePurposeTestRoot};export default {app};');
  const { userDataStorage } = await import(pathToFileURL(compile('main/runtimeKernel/storageRootResolver.ts')).href);
  const { PersistQueue } = await import(pathToFileURL(compile('main/persistQueue.ts')).href);
  const { Store } = await import(pathToFileURL(compile('main/store.ts')).href);
  const { ConfigManager } = await import(pathToFileURL(compile('main/config.ts')).href);
  const root = path.join(temp, 'current'); fs.mkdirSync(root);
  globalThis.__storagePurposeTestRoot = root;
  fs.writeFileSync(path.join(root, 'config.json'), JSON.stringify({ showWaitingTips: false }));
  assert.equal(new ConfigManager().get().showWaitingTips, false, 'existing config stays readable in place');
  const store = new Store();
  store.saveSessions([{ id: 's1', name: 'existing' }]); store.flushSync();
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'sessions.json'), 'utf8'))[0].id, 's1');
  await store.saveSessionsStrict(() => [{ id: 's2', name: 'strict' }]);
  assert.equal(new Store().loadSessions()[0].id, 's2');
  store.savePromptTasks([{ id: 'p1' }]);
  fs.writeFileSync(path.join(root, 'prompt-tasks.json'), 'damaged');
  assert.equal(store.loadPromptTasks()[0].id, 'p1', 'registry backup restores the same purpose target');
  const storage = userDataStorage(root);
  assert.throws(() => storage.fileByName('../config.json'), /Unregistered/);
  assert.throws(() => storage.fileByName('unknown.json'), /Unregistered/);
  const queue = new PersistQueue(path.join(temp, 'unused'), { resolveFile: file => storage.fileByName(file) });
  queue.write('usage-stats.json', { n: 1 }); await queue.flush();
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'usage-stats.json'), 'utf8')).n, 1);
  queue.write('usage-stats.json', { n: 2 }); queue.drop('usage-stats.json'); await queue.flush();
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'usage-stats.json'), 'utf8')).n, 1);
  await queue.writeStrict('usage-stats.json', () => ({ n: 3 }));
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'usage-stats.json'), 'utf8')).n, 3);
  assert.equal(fs.existsSync(path.join(temp, 'unused')), false);
  globalThis.__storagePurposeTestRoot = path.join(temp, 'metaagent-workbench');
  assert.throws(() => new Store(), /legacy product storage/);
  assert.throws(() => new ConfigManager(), /legacy product storage/);
  assert.equal(fs.existsSync(globalThis.__storagePurposeTestRoot), false);
  console.log('Store storage routing: existing config, queue/strict/drop, registry backup and legacy refusal passed');
} finally { delete globalThis.__storagePurposeTestRoot; fs.rmSync(temp, { recursive: true, force: true }); }
