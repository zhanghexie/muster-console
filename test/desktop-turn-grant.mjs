import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-turn-grant-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { DesktopTurnGrants } = await import(pathToFileURL(compile('main/desktop/turnGrant.ts')));
  let now = 0, prompts = 0;
  const grants = new DesktopTurnGrants(() => now, 100);
  const audits = [];
  const authorize = (id = 'session') => grants.authorize(id, () => true, async () => { prompts++; return true; }, value => audits.push(value));
  const [first, concurrent] = await Promise.all([authorize(), authorize()]);
  assert.equal(prompts, 1);
  assert.equal(first(), true);
  assert.equal(concurrent(), true);
  await authorize();
  assert.equal(prompts, 1);
  await authorize('other');
  assert.equal(prompts, 2, 'session grants are isolated');
  const oldTurn = grants.capture('session');
  grants.nextUserMessage('session');
  assert.equal(oldTurn(), false, 'an operation created before a message cannot acquire the new turn');
  assert.equal(first(), false, 'a new user message fences existing operations');
  const next = await authorize();
  assert.equal(prompts, 3);
  assert.equal(first(), false, 'later authorization cannot revive an older operation');
  now = 100;
  const waitingOperation = async () => { await Promise.resolve(); return next() ? 'dispatch' : 'blocked'; };
  assert.equal(next(), false, 'TTL expires at its boundary');
  const refreshed = await authorize();
  assert.equal(prompts, 4);
  assert.equal(refreshed(), true);
  assert.equal(next(), false, 'renewal cannot revive an expired authorization');
  assert.equal(await waitingOperation(), 'blocked', 'an in-flight operation remains blocked after renewal');
  const endFirst = grants.beginUserDelivery('transition');
  const endSecond = grants.beginUserDelivery('transition');
  await assert.rejects(authorize('transition'), /turn changed/);
  endFirst(); endFirst();
  await assert.rejects(authorize('transition'), /turn changed/, 'nested delivery stays blocked');
  endSecond();
  const afterTransition = await authorize('transition');
  assert.equal(afterTransition(), true);
  grants.noteNativeMessage('session', 'queued');
  assert.equal(grants.consumeNativeMessage('other', 'queued'), false);
  assert.equal(grants.consumeNativeMessage('session', 'queued'), true);
  assert.equal(grants.consumeNativeMessage('session', 'queued'), false);
  let finish, entered;
  const started = new Promise(resolve => { entered = resolve; });
  const pending = grants.authorize('pending', () => true, () => new Promise(resolve => { finish = resolve; entered(); }), value => audits.push(value));
  await started;
  grants.nextUserMessage('pending');
  finish(true);
  await assert.rejects(pending, /turn changed/);
  assert.equal(grants.current('pending'), false);
  await assert.rejects(grants.authorize('denied', () => true, async () => false, value => audits.push(value)), /declined/);
  assert.equal(grants.current('denied'), false);
  assert.deepEqual(audits, [true, true, true, true, true, true, false]);
  console.log('desktop turn grants: concurrency, session isolation, revocation, TTL, pending and denial passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
