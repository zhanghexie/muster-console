import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-chain-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { UnknownActionChains } = await import(pathToFileURL(compile('main/desktop/unknownActionChain.ts')));
  const { DesktopDispatchJournal } = await import(pathToFileURL(compile('main/desktop/dispatchJournal.ts')));
  const journalDir = path.join(temp, 'journal');
  const chain = new UnknownActionChains(new DesktopDispatchJournal(journalDir));
  const request = { taskId: 'task', appId: 'app', processInstance: 'p1', surfaceId: 'w1', surfaceGeneration: 'g1',
    captureId: 'capture', geometryRevision: 'geometry', region: { x: 0, y: 0, width: 10, height: 10 }, actionClass: 'input', evidenceSha256: 'a'.repeat(64) };
  let prompts = 0;
  const decisions = [];
  const confirm = async () => { prompts++; return true; };
  const audit = async (boundary, decision) => { decisions.push([boundary.evidenceSha256, decision]); };
  await Promise.all([chain.authorize(request, confirm, audit), chain.authorize(request, confirm, audit)]);
  assert.equal(prompts, 1, 'concurrent same-chain actions share one approval');
  await chain.authorize({ ...request, evidenceSha256: 'b'.repeat(64) }, confirm, audit);
  assert.equal(prompts, 1, 'subsequent evidence does not force per-click approval');
  await chain.authorize({ ...request, appId: 'other' }, confirm, audit);
  await chain.authorize(request, confirm, audit);
  await chain.authorize({ ...request, actionClass: 'submit' }, confirm, audit);
  assert.equal(prompts, 4, 'app changes and action-class changes invalidate the old chain');
  chain.invalidate('task');
  await chain.authorize(request, confirm, audit);
  assert.equal(prompts, 5, 'takeover and task end invalidate the chain');
  await assert.rejects(chain.authorize({ ...request, actionClass: 'deny' }, async () => false, audit), /declined/);
  await assert.rejects(chain.authorize({ ...request, actionClass: 'deny' }, confirm, audit), /previously declined/);
  const restarted = new UnknownActionChains(new DesktopDispatchJournal(journalDir));
  await assert.rejects(restarted.authorize({ ...request, actionClass: 'deny' }, confirm, audit), /previously declined/);
  const priorPrompts = prompts;
  await restarted.authorize({ ...request, actionClass: 'deny' }, confirm, audit, () => true);
  assert.equal(prompts, priorPrompts, 'current turn grant bypasses a persisted refusal without prompting');
  await assert.rejects(restarted.authorize({ ...request, actionClass: 'deny' }, confirm, audit), /previously declined/, 'refusal remains after turn grant ends');
  await assert.rejects(chain.clearRefusalAfterUserRequest('task', 'app', 'deny', async () => { throw new Error('audit failed'); }), /audit failed/);
  await assert.rejects(restarted.authorize({ ...request, actionClass: 'deny' }, confirm, audit), /previously declined/);
  await chain.clearRefusalAfterUserRequest('task', 'app', 'deny', async () => {});
  await chain.authorize({ ...request, actionClass: 'deny' }, confirm, audit);
  assert.deepEqual(decisions[0], ['a'.repeat(64), 'allowed']);
  await assert.rejects(chain.authorize({ ...request, evidenceSha256: 'bad' }, confirm, audit), /Invalid/);
  let release, entered;
  const started = new Promise(resolve => { entered = resolve; });
  const pending = chain.authorize({ ...request, actionClass: 'new' }, () => new Promise(resolve => { release = resolve; entered(); }), audit);
  await started;
  chain.invalidate('task');
  release(true);
  await assert.rejects(pending, /invalidated/);
  await assert.rejects(chain.authorize({ ...request, actionClass: 'new' }, confirm, async () => { throw new Error('audit failed'); }), /audit failed/);
  await chain.authorize({ ...request, actionClass: 'new' }, confirm, audit);
  let clock = 0;
  const expiring = new UnknownActionChains(new DesktopDispatchJournal(path.join(temp, 'expiry')), () => clock);
  const oldToken = await expiring.authorize(request, confirm, audit);
  clock = 24 * 60 * 60 * 1000;
  assert.equal(expiring.isAuthorized('task', 'app', 'input', oldToken), false);
  const newToken = await expiring.authorize(request, confirm, audit);
  assert.notEqual(oldToken, newToken);
  assert.equal(expiring.isAuthorized('task', 'app', 'input', oldToken), false, 'fresh approval cannot revive an expired token');
  assert.equal(expiring.isAuthorized('task', 'app', 'input', newToken), true);
  await expiring.authorize({ ...request, appId: 'other' }, confirm, audit);
  await expiring.authorize(request, confirm, audit);
  assert.equal(expiring.isAuthorized('task', 'app', 'input', newToken), false, 'switching away and back cannot revive an old token');
  const scoped = new UnknownActionChains(new DesktopDispatchJournal(path.join(temp, 'evidence-scope')));
  let scopePrompts = 0;
  const scopeConfirm = async () => { scopePrompts++; return true; };
  await scoped.authorize(request, scopeConfirm, audit);
  await scoped.authorize({ ...request, captureId: 'new-capture', evidenceSha256: 'b'.repeat(64) }, scopeConfirm, audit);
  assert.equal(scopePrompts, 1, 'fresh evidence of the same region reuses approval');
  await scoped.authorize({ ...request, region: { ...request.region, x: 1 } }, scopeConfirm, audit);
  assert.equal(scopePrompts, 2, 'changing the screenshot region requires new confirmation');
  await scoped.authorize({ ...request, surfaceGeneration: 'new-window' }, scopeConfirm, audit);
  assert.equal(scopePrompts, 3, 'replacing a window requires new confirmation');
  console.log('unknown desktop action chain: scope, concurrency, denial, takeover and audit passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
