import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const root = process.cwd();
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'memory-quality-'));
const compile = createSharedCompiler(root, temp);
const load = async (p) => import(pathToFileURL(compile(`main/memory/${p}.ts`)));
const { planConsolidationWrite, sha256Content } = await load('consolidation/apply');
const { enqueueConsolidationApproval, consolidationApprovalFileHooks } = await load('consolidation/approval');
const { MemoryDb } = await load('db');
const text = '项目背景：用户要求初始化仓库并编写文档。';
const now = new Date('2026-10-18T04:00:00Z');
const base = {currentContent:'',ops:[1,2,3].map(candidateId=>({op:'add',candidateId,text,confidence:0.99})),evidence:[1,2,3].map(stagingId=>({stagingId,origin:'worker'})),budgetChars:16000,surface:'worker',now};
const batch = planConsolidationWrite(base);
assert.equal(batch.applied.length,1,'different candidates with the same final body must not multiply');
assert.equal(batch.rejected.filter(r=>r.category==='duplicate').length,2);
const repeat = planConsolidationWrite({...base,currentContent:batch.content,ops:[{op:'add',candidateId:4,text:'#新标签 '+text,confidence:0.99}],evidence:[{stagingId:4}]});
assert.equal(repeat.applied.length,0,'tags and source citations do not constitute new information');
const different = planConsolidationWrite({...base,currentContent:batch.content,ops:[{op:'add',candidateId:4,text:'Linux可使用此命令，Windows必须使用另一命令。',confidence:0.99}],evidence:[{stagingId:4}]});
assert.equal(different.applied.length,1,'distinct conditions must survive');
const raw = new DatabaseSync(':memory:');
raw.exec(`CREATE TABLE approvals(id INTEGER PRIMARY KEY,action TEXT,payload TEXT,confidence REAL,state TEXT,created_at INTEGER);
CREATE TABLE staging(id INTEGER PRIMARY KEY,state TEXT);
CREATE TABLE memory_events(id INTEGER PRIMARY KEY,kind TEXT,ts INTEGER,namespace TEXT,staging_id INTEGER,approval_id INTEGER,chunk_id INTEGER,entry_ref TEXT,summary TEXT,summary_args TEXT);
INSERT INTO staging VALUES(1,'pending');`);
const db = new MemoryDb(':memory:',raw);
const proposal = {namespace:'worker',targetFileRel:'docs/memory/MEMORY.md',baseHash:sha256Content(''),baseContentChars:0,operations:[{op:'add',candidateId:1,stagingId:1,text,confidence:0.6,citation:'Source: test'}],reason:'test',now:+now};
const first = enqueueConsolidationApproval(db,proposal);
assert.equal(enqueueConsolidationApproval(db,{...proposal,operations:[{...proposal.operations[0],text:'同一候选的另一种措辞'}]}),first);
assert.equal(raw.prepare('SELECT COUNT(*) n FROM approvals').get().n,1);
const hooks = consolidationApprovalFileHooks(db,first,proposal,{surface:'worker',now:+now,budgetChars:16000,evidence:[{stagingId:1}]});
assert.equal(hooks.buildPlan(batch.content).appliedCount,0,'stale proposals must not append');
raw.exec("UPDATE staging SET state='promoted'");
assert.equal(hooks.buildPlan('').appliedCount,0,'a settled candidate cannot be promoted by another proposal');
db.close();
console.log('memory-quality-invariants: 7 checks passed');
