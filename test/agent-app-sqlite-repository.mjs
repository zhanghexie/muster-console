/** Exercise the repository actually used by the service worker. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { DatabaseSync } from 'node:sqlite';
import { buildSync } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const tempRoot = fs.realpathSync(os.tmpdir());
const folder = fs.mkdtempSync(path.join(tempRoot, 'agent-app-repository-'));
if (path.dirname(fs.realpathSync(folder)) !== tempRoot) throw new Error('Unexpected test directory');
let repository;
try {
  const bundle = path.join(folder, 'repository.cjs');
  buildSync({ entryPoints: [path.join(root, 'src/main/agentApps/sqliteRepository.ts')], outfile: bundle, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  const { AgentAppsSqliteRepository } = createRequire(import.meta.url)(bundle);
  const data = path.join(folder, 'data');
  repository = new AgentAppsSqliteRepository(data);
  assert.equal(repository.open('one').revision, 0);
  const rows = Array.from({ length: 2000 }, (_, index) => ({ id: `row-${index}`, collection: 'items', revision: index === 1999 ? 7 : 1, createdAt: index, updatedAt: index, values: { title: index === 1999 ? '中文 MiXeD' : `item ${index}`, done: index % 2 === 0, ...(index === 1999 ? { status: 'open', externalId: 'ext-1999', dueAt: '2026-11-20T12:00:00.000Z' } : {}) } }));
  const changes = rows.map(record => ({ type: 'putRecord', appId: 'notes', record }));
  changes.push({ type: 'putJob', value: { id: 'job-1', kind: 'reminder', appId: 'notes', commandId: 'due', params: { id: 'row-1' }, dueAt: 10, enabled: true, revision: 1, attempts: 0, missed: 'catch-up' } });
  changes.push({ type: 'putOutbox', value: { id: 'event-1', appId: 'notes', kind: 'reminder.due', recordIds: ['row-1'], title: 'Reminder', createdAt: 10, attempts: 0, nextAttemptAt: 10, action: 'wake' } });
  assert.equal(repository.transact('one', 0, changes).revision, 1);
  assert.throws(() => repository.transact('one', 1, [{ type: 'putRecord', appId: 'notes', record: { ...rows[0], id: 'must-roll-back' } }, { type: 'not-an-operation' }]), /unknown/i);
  assert.equal(repository.open('one').revision, 1, 'failed transactions do not advance revision');
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', id: 'must-roll-back' }).total, 0);
  assert.throws(() => repository.transact('one', 1, [{ type: 'putRecord', appId: 'notes', record: { ...rows[0], id: 'oversized-extension', extensionPayload: 'x'.repeat(64_001) } }]), /extension fields/i);
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', id: 'oversized-extension' }).total, 0, 'oversized extension payload is rejected atomically');
  const found = repository.query('one', { appId: 'notes', collection: 'items', search: 'mixed', limit: 5 });
  assert.equal(found.total, 1); assert.equal(found.records[0].id, 'row-1999');
  const ftsRows = repository.databases.get('one').prepare('SELECT app_id,record_id FROM records_fts WHERE records_fts MATCH ?').all('"mixed"').map(row => ({ app_id: row.app_id, record_id: row.record_id }));
  assert.deepEqual(ftsRows, [{ app_id: 'notes', record_id: 'row-1999' }], 'record search uses the derived FTS5 index');
  const filtered = repository.query('one', { appId: 'notes', collection: 'items', filter: { done: true }, offset: 1, limit: 3 });
  assert.equal(filtered.total, 1000); assert.deepEqual(filtered.records.map(row => row.id), ['row-1996', 'row-1994', 'row-1992']);
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', offset: 1_000_001, limit: 3 }).records.length, 0, 'offsets are bounded before reaching SQLite');
  assert.throws(() => repository.query('one', { appId: 'notes', collection: 'items', offset: Number.NaN }), /offset must be a safe integer/);
  assert.throws(() => repository.query('one', { appId: 'notes', collection: 'items', limit: Number.POSITIVE_INFINITY }), /limit must be a safe integer/);
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', limit: 201 }).records.length, 200, 'limit remains capped at 200');
  assert.deepEqual(repository.query('one', { appId: 'notes', collection: 'items', filter: { status: 'open' } }).records.map(row => row.id), ['row-1999']);
  assert.deepEqual(repository.query('one', { appId: 'notes', collection: 'items', filter: { externalId: 'ext-1999' } }).records.map(row => row.id), ['row-1999']);
  assert.deepEqual(repository.query('one', { appId: 'notes', collection: 'items', filter: { dueAt: '2026-11-20T12:00:00.000Z' } }).records.map(row => row.id), ['row-1999']);
  assert.deepEqual(repository.query('one', { appId: 'notes', collection: 'items', filter: { revision: 7 } }).records.map(row => row.id), ['row-1999']);
  const recordColumns = new Set((repository.databases.get('one').prepare('PRAGMA table_info(records)').all()).map(row => row.name));
  for (const column of ['app_id', 'record_revision', 'status', 'external_id', 'due_at']) assert.equal(recordColumns.has(column), true, `records has ${column} hot column`);
  assert.equal(recordColumns.has('search_values'), false, 'search text is retained only in the rebuildable FTS5 projection');
  const recordIndexes = new Set((repository.databases.get('one').prepare("SELECT name FROM sqlite_schema WHERE type='index' AND tbl_name='records'").all()).map(row => row.name));
  for (const index of ['records_status', 'records_external_id', 'records_due_at', 'records_revision']) assert.equal(recordIndexes.has(index), true, `records has ${index} index`);
  const storedPayload = JSON.parse(repository.databases.get('one').prepare('SELECT value FROM records WHERE app_id=? AND id=?').get('notes', 'row-1999').value);
  assert.equal(storedPayload.id, undefined); assert.equal(storedPayload.revision, undefined); assert.equal(storedPayload.values.status, undefined); assert.equal(storedPayload.values.externalId, undefined); assert.equal(storedPayload.values.dueAt, undefined);
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', search: 'mi', limit: 10 }).records.some(row => row.id === 'row-1999'), true, 'short searches use the same derived FTS5 projection');
  repository.transact('one', 1, [{ type: 'deleteRecord', appId: 'notes', id: 'row-1' }]);
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', search: 'item 1', limit: 200 }).records.some(row => row.id === 'row-1'), false, 'deleting a record removes its derived search row');
  repository.databases.get('one').prepare('DELETE FROM records_fts WHERE app_id=? AND record_id=?').run('notes', 'row-1999');
  repository.databases.get('one').prepare("UPDATE meta SET value='0' WHERE key='records_fts_version'").run();
  repository.closeWorkspace('one');
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items', search: 'mixed' }).total, 1, 'opening a store rebuilds a missing derived search index');
  assert.throws(() => repository.transact('one', 1, [{ type: 'deleteRecord', appId: 'notes', id: 'row-2' }]), /revision/i);
  assert.equal(repository.open('two').revision, 0);
  assert.equal(repository.query('two', { appId: 'notes', collection: 'items' }).total, 0);
  const secondDb = repository.databases.get('two');
  const realClose = secondDb.close.bind(secondDb);
  secondDb.close = () => { throw new Error('fixture close failure'); };
  assert.throws(() => repository.closeWorkspace('two'), /fixture close failure/);
  assert.equal(repository.databases.get('two'), secondDb, 'failed close retains the handle for retry');
  secondDb.close = realClose;
  repository.closeWorkspace('two');
  assert.equal(repository.databases.has('two'), false);
  assert.equal(repository.open('two').revision, 0, 'a closed workspace can be reopened');
  repository.close();
  repository = new AgentAppsSqliteRepository(data);
  assert.equal(repository.open('one').revision, 2);
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items' }).total, 1999);
  assert.equal(repository.list('one', 'jobs')[0].id, 'job-1');
  assert.equal(repository.list('one', 'outbox')[0].id, 'event-1');
  repository.open('broken-schema');
  const badPath = path.join(data, `${createHash('sha256').update('bad').digest('hex')}.sqlite`);
  fs.writeFileSync(badPath, 'not a sqlite database');
  assert.throws(() => repository.open('bad'), /database|sqlite/i);
  assert.equal(fs.readFileSync(badPath, 'utf8'), 'not a sqlite database');
  assert.equal(repository.query('one', { appId: 'notes', collection: 'items' }).total, 1999);
  repository.close(); repository = undefined;
  const brokenSchemaPath = path.join(data, `${createHash('sha256').update('broken-schema').digest('hex')}.sqlite`);
  const tamper = new DatabaseSync(brokenSchemaPath); tamper.exec('DROP TABLE records'); tamper.close();
  repository = new AgentAppsSqliteRepository(data);
  assert.throws(() => repository.open('broken-schema'), /schema.*incomplete/i);
  const legacyPath = path.join(data, `${createHash('sha256').update('legacy').digest('hex')}.sqlite`);
  const legacy = new DatabaseSync(legacyPath);
  legacy.exec(`
    CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE installations (id TEXT PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE record_groups (id TEXT PRIMARY KEY);
    CREATE TABLE records (app_id TEXT NOT NULL, id TEXT NOT NULL, collection_id TEXT NOT NULL, updated_at INTEGER NOT NULL, value TEXT NOT NULL, search_values TEXT NOT NULL, PRIMARY KEY(app_id,id));
    CREATE TABLE image_assets (id TEXT PRIMARY KEY, app_id TEXT NOT NULL, deleting INTEGER NOT NULL DEFAULT 0, value TEXT NOT NULL);
    CREATE TABLE image_references (app_id TEXT NOT NULL, record_id TEXT NOT NULL, asset_id TEXT NOT NULL, PRIMARY KEY(app_id,record_id,asset_id));
    CREATE TABLE jobs (id TEXT PRIMARY KEY, app_id TEXT NOT NULL, kind TEXT NOT NULL, due_at INTEGER NOT NULL, enabled INTEGER NOT NULL, value TEXT NOT NULL);
    CREATE TABLE outbox (id TEXT PRIMARY KEY, app_id TEXT NOT NULL, next_attempt_at INTEGER NOT NULL, delivered_at INTEGER, value TEXT NOT NULL);
    CREATE TABLE receipts (id TEXT PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE connections (id TEXT PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE operations (id TEXT PRIMARY KEY, value TEXT NOT NULL);
    CREATE TABLE extras (id TEXT PRIMARY KEY, value TEXT NOT NULL);
    INSERT INTO meta(key,value) VALUES ('workspaceId','legacy'),('revision','0');
    INSERT INTO records(app_id,id,collection_id,updated_at,value,search_values) VALUES ('notes','legacy-record','items',5,'{"id":"legacy-record","collection":"items","revision":3,"createdAt":5,"updatedAt":5,"values":{"status":"draft","externalId":"legacy-ext","dueAt":"2026-11-21T12:00:00.000Z"}}','["draft","legacy-ext"]');
    PRAGMA user_version=1;
  `);
  legacy.close();
  assert.throws(() => repository.open('legacy'), /schema.*incomplete/i);
  const legacyCheck = new DatabaseSync(legacyPath);
  const legacyRow = legacyCheck.prepare('SELECT value FROM records WHERE id=?').get('legacy-record');
  assert.match(legacyRow.value, /\"revision\":3/);
  assert.equal(legacyCheck.prepare('PRAGMA user_version').get().user_version, 1);
  legacyCheck.close();
  console.log('agent app SQLite repository: incremental rows, transaction CAS, isolation, restart and corruption passed');
} finally {
  repository?.close();
  fs.rmSync(folder, { recursive: true, force: true });
}
