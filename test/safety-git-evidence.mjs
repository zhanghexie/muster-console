import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'safety-git-view-'));
try {
  const compile = createSharedCompiler(process.cwd(), directory);
  const { createSafetyGitEvidenceCollector, createSafetyGitEvidenceView } = await import(pathToFileURL(compile('main/safety/evidence.ts')));
  const digest = text => createHash('sha256').update(text).digest('hex');
  const diff = `diff --git a/first b/first\n+${'first line\n'.repeat(6000)}diff --git a/second b/second\n+SECOND_FILE_END`;
  const parts = { diff, workingDiff: '', stagedDiff: '', commits: 'fixture commit\n' };
  const repo = root => ({ root, source:'source-sha', target:'target-sha', sourceRef:'feature', targetRef:'main',
    status:{files:[{path:'first',index:' ',working_dir:'M'}]}, untrackedFiles:[{path:'new',type:'file',sha256:'hash'}],
    tests:'unavailable', ...Object.fromEntries(Object.entries(parts).map(([key, text]) => [key, { text:text.slice(0,48000), truncated:text.length>48000, sha256:digest(text) }])) });
  const snapshot = JSON.stringify({ sessions:[{session:{id:'s',name:'Fixture'},repositories:[repo('/tree'),repo('/main')]}] });
  const collector = createSafetyGitEvidenceCollector();
  collector.capture('s','/tree',parts); collector.capture('s','/main',parts);
  const source = collector.finish(snapshot);
  assert.equal(source.incomplete,false);
  assert.equal(source.repositories[0].content.diff,source.repositories[1].content.diff,'identical worktree and target diffs share one capture');
  assert.equal(Object.values(source.contents).filter(value=>value===diff).length,1);
  const view = createSafetyGitEvidenceView(source);
  assert.equal(JSON.stringify(view.summary).includes('SECOND_FILE_END'),false,'initial request contains no diff body');
  assert.equal(view.summary.repositoryCount,2);
  const listed = view.query({action:'files',repositoryId:'repo-0',part:'diff',offset:1,limit:1});
  assert.equal(listed.result.total,2);assert.match(listed.result.items[0].header,/second/);
  assert.equal(view.query({action:'files'}).result.repositoryId,'repo-0','identical captured diffs make the default unambiguous');
  const read = view.query({action:'read',repositoryId:'repo-0',part:'diff',fileId:1,offset:0,limit:6000});
  assert.match(read.result.text,/SECOND_FILE_END/,'a file beyond the old 48k preview remains readable');
  assert.equal(read.contentRead,true);
  assert.equal(view.query({action:'read',repositoryId:'repo-0',part:'diff',fileId:1,offset:9999}).contentRead,false,'empty pages cannot satisfy evidence reading');
  assert.equal(view.query({action:'read',repositoryId:'repo-0',part:'diff',fileId:0,limit:1}).contentRead,false,'a token-length fragment cannot satisfy evidence reading');
  assert.equal(view.query({action:'status',repositoryId:'repo-1'}).result.total,1);
  assert.equal(view.query({action:'untracked',repositoryId:'repo-1'}).result.total,1);
  const outside = view.query({action:'read',repositoryId:'outside',part:'diff',fileId:0});
  assert.equal(outside.selectionError,true);assert.equal(outside.result.code,'repository_selection_required');
  assert.equal(JSON.stringify(outside.result).includes('outside'),false,'an untrusted repository id is never treated as a path or echoed');
  const missingFile=view.query({action:'read',repositoryId:'repo-0',part:'diff',fileId:999});
  assert.equal(missingFile.selectionError,true);assert.equal(missingFile.result.code,'file_selection_required');
  assert.deepEqual(missingFile.result.files.map(item=>item.fileId),[0,1]);
  assert.throws(()=>view.query({action:'repositories',offset:-1}),/分页/);
  assert.equal(view.query({action:'read',repositoryId:'repo-0',fileId:0,limit:6001}).result.text.length,6000,'omitted part defaults to diff and oversized pages are capped');
  assert.equal(view.query({action:'repositories',limit:100}).result.limit,30);
  const otherParts={...parts,diff:'diff --git a/other b/other\n+different\n'};
  collector.capture('s','/other',otherParts);
  const otherRepo={...repo('/other'),...Object.fromEntries(Object.entries(otherParts).map(([key,text])=>[key,{sha256:digest(text),text,truncated:false}]))};
  const different=createSafetyGitEvidenceView(collector.finish(JSON.stringify({sessions:[{session:{id:'s'},repositories:[repo('/tree'),otherRepo]}]})));
  const ambiguous=different.query({action:'files'});
  assert.equal(ambiguous.selectionError,true);assert.equal(ambiguous.result.code,'repository_selection_required');
  assert.deepEqual(ambiguous.result.repositories.map(item=>item.id),['repo-0','repo-1']);
  assert.equal(different.query({action:'files',repositoryId:'repo-0'}).result.repositoryId,'repo-0');
  const unavailableSource={...source,incomplete:true,repositories:[source.repositories[0],{...source.repositories[1],unavailable:'fixture missing repository'}]};
  const unavailableView=createSafetyGitEvidenceView(unavailableSource);
  assert.equal(unavailableView.unavailableReason,'repo-1: fixture missing repository');
  assert.equal(unavailableView.query({action:'files'}).selectionError,true,'a missing repository prevents an implicit equivalence selection');
  const unavailable=unavailableView.query({action:'files',repositoryId:'repo-1'});
  assert.equal(unavailable.result.code,'repository_unavailable');assert.equal(unavailable.result.reason,'fixture missing repository');
  const bounded = createSafetyGitEvidenceCollector(10); bounded.capture('s','/tree',parts);
  const incomplete = bounded.finish(JSON.stringify({sessions:[{session:{id:'s'},repositories:[repo('/tree')]}]}));
  assert.equal(incomplete.incomplete,true,'evidence omitted due to memory limits is never represented as complete');
  assert.throws(()=>createSafetyGitEvidenceView(incomplete).query({action:'files',repositoryId:'repo-0',part:'diff'}),/不可用/);
  const missing = createSafetyGitEvidenceCollector().finish(snapshot);
  assert.equal(missing.incomplete,true,'missing capture is not silently authorized');
  const cleanParts = {diff:'',workingDiff:'',stagedDiff:'',commits:''};
  const statusRepo = { ...repo('/status'), ...Object.fromEntries(Object.entries(cleanParts).map(([key,text])=>[key,{sha256:digest(text),text,truncated:false}])) };
  const statusCollector = createSafetyGitEvidenceCollector();statusCollector.capture('s','/status',cleanParts);
  const statusView = createSafetyGitEvidenceView(statusCollector.finish(JSON.stringify({sessions:[{session:{id:'s'},repositories:[statusRepo]}]})));
  assert.equal(statusView.query({action:'repositories'}).contentRead,false,'a count does not inspect existing changed or untracked paths');
  assert.equal(statusView.query({action:'status',offset:99}).contentRead,false,'an empty status page cannot satisfy evidence reading');
  assert.equal(statusView.query({action:'status'}).contentRead,true,'the actual status can be reviewed when there is no diff');
  collector.clear(); assert.deepEqual(Object.keys(source.contents),[],'captured code can be released after the operation');
  console.log('safety git evidence paging and scope passed');
} finally { fs.rmSync(directory,{recursive:true,force:true}); }
