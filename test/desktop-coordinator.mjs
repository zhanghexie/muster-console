import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
import { removeWorkspaceFixture } from './helpers/workspace-fixture.mjs';

fs.mkdirSync('.tmp', { recursive: true });
const temp = fs.mkdtempSync(path.resolve('.tmp', 'desktop-coordinator-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { DesktopCoordinator } = await import(pathToFileURL(compile('main/desktop/desktopCoordinator.ts')));
  const { PreDispatchFailure } = await import(pathToFileURL(compile('main/desktop/preDispatchFailure.ts')));
  let releaseCount = 0, enter, finish;
  const entered = new Promise(resolve => { enter = resolve; });
  const waiting = new Promise(resolve => { finish = resolve; });
  const states = new Map();
  const coordinator = new DesktopCoordinator(async () => { releaseCount++; }, (owner, state) => states.set(owner, state));
  const a = await coordinator.start('worker-a');
  const b = await coordinator.start('worker-b');
  const active = coordinator.execute('worker-a', a, async signal => { enter(signal); await waiting; return 'wrong'; });
  const signal = await entered;
  let queuedRan = false;
  const queued = coordinator.execute('worker-b', b, async () => { queuedRan = true; });
  // Observe rejections immediately; both operations are expected to be cancelled.
  const activeResult = active.then(() => null, error => error);
  const queuedResult = queued.then(() => null, error => error);
  let stopped = false;
  const stop = coordinator.stop().then(() => { stopped = true; });
  await Promise.resolve();
  assert.equal(signal.aborted, true);
  assert.equal(stopped, false, 'a backend that ignores abort must keep the seat stopping');
  await assert.rejects(coordinator.execute('worker-b', b, async () => {}), /not active/);
  finish();
  await stop;
  assert.ok(await activeResult);
  assert.ok(await queuedResult);
  assert.equal(states.get('worker-a'), 'unknown', 'a dispatched action without a result is uncertain');
  assert.equal(queuedRan, false);
  assert.ok(releaseCount >= 2);
  await assert.rejects(coordinator.start('worker-b'), /new user instruction/);
  const racingResume = coordinator.resumeForUserInstruction();
  await coordinator.stop();
  await assert.rejects(racingResume, /restart was stopped/, 'a later stop must defeat an earlier resume');
  await assert.rejects(coordinator.start('worker-b'), /new user instruction/);
  await coordinator.resumeForUserInstruction();
  const next = await coordinator.start('worker-b');
  coordinator.finish('worker-b', b);
  await assert.rejects(coordinator.execute('worker-b', b, async () => 0), /not active/);
  assert.equal(await coordinator.execute('worker-b', next, async () => 42), 42);
  const failedStates = [];
  const failed = new DesktopCoordinator(async () => { throw new Error('release failed'); }, (_owner, state) => failedStates.push(state));
  await failed.start('worker-c');
  await assert.rejects(failed.stop(), /release failed/);
  assert.deepEqual(failedStates, ['active', 'stopping', 'unknown']);
  await assert.rejects(failed.start('worker-c'), /release failed/);
  let releaseBlockedAction, releaseBlockedStarted;
  const releaseEntered = new Promise(resolve => { releaseBlockedStarted = resolve; });
  const releaseGate = new Promise(resolve => { releaseBlockedAction = resolve; });
  const releaseFailedDuringAction = new DesktopCoordinator(async () => { throw new Error('release failed'); }, () => {});
  const releaseBlockedRun = await releaseFailedDuringAction.start('release-during-action');
  const releaseAction = releaseFailedDuringAction.execute('release-during-action', releaseBlockedRun, async signal => {
    releaseBlockedStarted(signal); await releaseGate;
  }).catch(error => error);
  const releaseSignal = await releaseEntered;
  let releaseStopSettled = false;
  const releaseStop = releaseFailedDuringAction.stop().then(() => { releaseStopSettled = true; }, error => { releaseStopSettled = true; return error; });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(releaseSignal.aborted, true);
  assert.equal(releaseStopSettled, false, 'release failure must not finish stopping while a backend is still running');
  releaseBlockedAction();
  assert.match(String(await releaseStop), /release failed/);
  assert.ok(await releaseAction);
  assert.equal(releaseBlockedRun.status, 'unknown');
  const noReason = new DesktopCoordinator(async () => { throw undefined; }, () => {});
  const noReasonRun = await noReason.start('no-reason');
  await assert.rejects(noReason.stop(), /undefined/, 'a rejected release with no reason must never be treated as success');
  assert.equal(noReasonRun.status, 'unknown');
  let rejectFirst, enteredFirst;
  const firstEntered = new Promise(resolve => { enteredFirst = resolve; });
  const unknownStates = [];
  const uncertain = new DesktopCoordinator(async () => {}, (_owner, state) => unknownStates.push(state));
  const unknownRun = await uncertain.start('worker-d');
  const first = uncertain.execute('worker-d', unknownRun, () => new Promise((_resolve, reject) => { rejectFirst = reject; enteredFirst(); }));
  const firstResult = first.catch(error => error);
  await firstEntered;
  let secondDispatched = false;
  const second = uncertain.execute('worker-d', unknownRun, async () => { secondDispatched = true; });
  const secondResult = second.catch(error => error);
  rejectFirst(new Error('result lost'));
  assert.ok(await firstResult);
  assert.ok(await secondResult, 'queued action must be rejected once an earlier outcome becomes unknown');
  assert.equal(secondDispatched, false, 'unknown must prevent already queued actions from dispatching');
  assert.equal(unknownStates.at(-1), 'unknown');
  let rejectAcross, enterAcross;
  const acrossStarted = new Promise(resolve => { enterAcross = resolve; });
  const across = new DesktopCoordinator(async () => {}, () => {});
  const acrossA = await across.start('across-a'), acrossB = await across.start('across-b');
  const acrossFirst = across.execute('across-a', acrossA, () => new Promise((_resolve, reject) => { rejectAcross = reject; enterAcross(); })).catch(error => error);
  await acrossStarted;
  let acrossRan = false;
  const acrossSecond = across.execute('across-b', acrossB, async () => { acrossRan = true; }).catch(error => error);
  rejectAcross(new Error('driver result lost'));
  assert.ok(await acrossFirst);
  assert.ok(await acrossSecond, 'an uncertain driver outcome must stop the shared seat');
  assert.equal(acrossRan, false, 'another worker cannot dispatch while seat outcome is unknown');
  const known = new DesktopCoordinator(async () => {}, () => {});
  const knownRun = await known.start('known');
  await assert.rejects(known.execute('known', knownRun, async () => { throw new PreDispatchFailure('invalid argument'); }), /invalid argument/);
  assert.equal(knownRun.status, 'active', 'a proven pre-dispatch failure must not mark the seat unknown');
  assert.equal(await known.execute('known', knownRun, async () => 42), 42);
  const readOnly = new DesktopCoordinator(async () => {}, () => {});
  const readRun = await readOnly.start('reader');
  await assert.rejects(readOnly.execute('reader', readRun, async () => { throw new Error('observation failed'); }, false), /observation failed/);
  assert.equal(readRun.status, 'active', 'an observation failure must not be labelled an uncertain write');
  assert.equal(await readOnly.execute('reader', readRun, async () => 6), 6);
  const readCleanup = new DesktopCoordinator(async () => { throw new Error('release failed'); }, () => {});
  const readCleanupRun = await readCleanup.start('read-cleanup');
  await assert.rejects(readCleanup.execute('read-cleanup', readCleanupRun, async () => 1, false), /release failed/);
  assert.equal(readCleanupRun.status, 'unknown', 'failed input cleanup is uncertain even after a read-only call');
  const releaseStates = [];
  const releaseError = new DesktopCoordinator(async () => { throw new PreDispatchFailure('cleanup failure'); }, (_owner, state) => releaseStates.push(state));
  const releaseRun = await releaseError.start('release-failure');
  await assert.rejects(releaseError.execute('release-failure', releaseRun, async () => 42), /cleanup failure/);
  assert.equal(releaseRun.status, 'unknown', 'a cleanup failure cannot masquerade as a pre-dispatch action failure');
  let reentrantStop;
  const reentrant = new DesktopCoordinator(async () => {}, (_owner, state) => {
    if (state === 'active') reentrantStop = reentrant.stop();
  });
  await assert.rejects(reentrant.start('worker-e'), /stopped/, 'stop during active notification must cancel startup');
  await reentrantStop;
  console.log('desktop coordinator: shared seat, stop latch and explicit restart passed');
} finally { removeWorkspaceFixture(temp, 'desktop-coordinator-'); }
