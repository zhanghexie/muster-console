import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { buildSync } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const tempRoot = fs.realpathSync(os.tmpdir());
const folder = fs.mkdtempSync(path.join(tempRoot, 'agent-app-library-'));
if (path.dirname(fs.realpathSync(folder)) !== tempRoot) throw new Error('Unexpected test directory');
const services = [];
try {
  const bundle = path.join(folder, 'service.cjs');
  buildSync({ stdin: { contents: "export { AgentAppsService } from './src/main/agentApps/service'; export { defineRecordApp } from './src/shared/agentApps';", resolveDir: root, sourcefile: 'library-fixture.ts' }, outfile: bundle, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  const { AgentAppsService, defineRecordApp } = createRequire(import.meta.url)(bundle);
  const createService = options => { const service = new AgentAppsService(options); services.push(service); return service; };
  let reviews = 0;
  const options = { root: path.join(folder, 'agent-apps'), workspaces: () => ['one', 'two', 'three'], emit() {}, encrypt: x => x, decrypt: x => x, confirmSend: async () => true, authorizeDefinition: async () => { reviews++; return true; }, deliver: async () => ({ muted: true }), connectors: { feed: async () => [], sync: async () => ({ records: [], cursor: {} }), send: async () => ({ messageId: 'unused' }), test: async () => {} } };
  let service = createService(options);
  const makeApp = (id, name) => defineRecordApp({ id, name, fields: [{ id: 'title', label: 'Title', type: 'text', required: true }], titleField: 'title' });
  const app = makeApp('shared-notes', 'Shared notes');
  const secretApp = makeApp('private-notes', 'Private notes');
  await service.install('one', app);
  await service.install('one', secretApp, { private: true });
  let library = service.listLibrary('two');
  const album = library.find(item => item.catalogId === 'template:photo-album');
  assert.equal(album?.appId, 'example-photo-album');
  assert.equal(album.canPublish, false);
  await service.installFromLibrary('two', album.catalogId);
  assert.ok(service.snapshot('two').apps.find(item => item.definition.id === album.appId).definition.collections[0].fields.some(field => field.type === 'image'));
  const albumDefinition = service.snapshot('two').apps.find(item => item.definition.id === album.appId).definition;
  const reviewTemplateChange = reviews;
  options.authorizeDefinition = async () => { reviews++; return false; };
  await assert.rejects(service.install('two', { ...albumDefinition, version: albumDefinition.version + 1, description: 'Changed template behavior' }), /approval denied/);
  assert.equal(reviews, reviewTemplateChange + 1, 'modifying bundled content must not bypass review');
  options.authorizeDefinition = async () => { reviews++; return true; };
  assert.equal(library.some(item => item.appId === 'private-notes'), false);
  const shared = library.find(item => item.appId === 'shared-notes');
  assert.ok(shared?.catalogId);
  assert.equal(shared.installedVersion, undefined);
  await assert.rejects(service.installFromLibrary('two', service.listLibrary('one').find(item => item.appId === 'private-notes').catalogId), /private|available|not found/i);
  const beforeReview = reviews;
  await service.installFromLibrary('two', shared.catalogId);
  assert.equal(reviews, beforeReview + 1, 'installing a shared definition still passes existing safety review');
  const beforeHumanReview = reviews;
  await service.installFromLibrary('three', shared.catalogId, undefined, 'human');
  assert.equal(reviews, beforeHumanReview, 'human installation from the library must not call the reviewer');
  service.store.transact('three', state => { const item = state.installations.find(entry => entry.definition.id === app.id); item.enabled = false; item.approvedDefinition = 'outdated'; });
  await service.setEnabled('three', app.id, true, 'human');
  assert.equal(reviews, beforeHumanReview, 'human enable does not review an altered definition');
  await service.setEnabled('three', app.id, false);
  service.store.transact('three', state => { state.installations.find(entry => entry.definition.id === app.id).approvedDefinition = 'outdated'; });
  options.authorizeDefinition = async () => { reviews++; return false; };
  await assert.rejects(service.setEnabled('three', app.id, true), /approval denied/);
  assert.equal(service.snapshot('three').apps.find(entry => entry.definition.id === app.id).enabled, false, 'denied agent enable has no effect');
  options.authorizeDefinition = async () => { reviews++; return true; };
  service.uninstall('three', app.id, true);
  const actor = { kind: 'human', runId: 'test' };
  const record = (await service.execute('two', { appId: app.id, commandId: 'create', params: { values: { title: 'workspace two only' } } }, actor)).record;
  assert.equal(service.query('one', { appId: app.id }).total, 0);
  const edited = { ...app, version: 2, description: 'Second edition' };
  await service.install('one', edited);
  assert.equal(service.listLibrary('two').find(item => item.catalogId === shared.catalogId).version, 1, 'local editing does not publish a version');
  service.publishToLibrary('one', app.id);
  library = service.listLibrary('two');
  assert.equal(library.find(item => item.catalogId === shared.catalogId).updateAvailable, true);
  assert.equal(service.snapshot('two').apps.find(item => item.definition.id === app.id).definition.version, 1, 'updates are never silently installed');
  await service.installFromLibrary('two', shared.catalogId);
  assert.equal(service.snapshot('two').apps.find(item => item.definition.id === app.id).definition.version, 2);
  assert.equal(service.query('two', { appId: app.id }).records[0].id, record.id);
  service.uninstall('two', app.id);
  await service.installFromLibrary('two', shared.catalogId);
  assert.equal(service.query('two', { appId: app.id }).records[0].id, record.id, 'reinstallation of the same catalog identity restores retained data');
  service.setLibraryPrivate('one', app.id, true);
  assert.equal(service.listLibrary('two').some(item => item.catalogId === shared.catalogId), false);
  assert.equal(service.query('two', { appId: app.id }).records[0].id, record.id, 'changing visibility does not uninstall existing copies');
  service.setLibraryPrivate('one', app.id, false);
  service = createService(options);
  assert.equal(service.listLibrary('two').find(item => item.catalogId === shared.catalogId).version, 2, 'library survives restart');
  await service.install('one', { ...edited, version: 3, description: 'Published third edition' });
  service.publishToLibrary('one', app.id);
  await service.install('two', { ...edited, version: 3, description: 'Competing third edition' });
  assert.throws(() => service.publishToLibrary('two', app.id), /conflict/i, 'stale local edits cannot overwrite a published version');
  assert.equal(service.listLibrary('one').find(item => item.catalogId === shared.catalogId).version, 3);
  await service.install('one', { ...edited, version: 4, description: 'Published fourth edition' });
  service.publishToLibrary('one', app.id);
  await assert.rejects(service.installFromLibrary('two', shared.catalogId), /unpublished|conflict/i, 'a library update must not overwrite local unpublished edits');
  assert.equal(service.snapshot('two').apps.find(item => item.definition.id === app.id).definition.description, 'Competing third edition');
  const oldApp = makeApp('old-app', 'Existing app');
  service.store.transact('three', state => state.installations.push({ definition: oldApp, enabled: true, installedAt: 1 }));
  service.start(); service.stop();
  assert.ok(service.listLibrary('two').some(item => item.appId === 'old-app'), 'existing installed apps are automatically registered');
  await service.install('three', makeApp('shared-notes', 'Different notes'));
  library = service.listLibrary('two').filter(item => item.appId === app.id);
  assert.equal(library.length, 2);
  assert.ok(library.every(item => item.conflict), 'same local app id with different definitions is visible as a conflict');
  await assert.rejects(service.installFromLibrary('two', library.find(item => item.catalogId !== shared.catalogId).catalogId), /conflict|already installed/i);
  const catalogFile = path.join(folder, 'agent-app-library', 'catalog.json');
  fs.writeFileSync(catalogFile, '{invalid catalog');
  assert.throws(() => service.listLibrary('two'), /JSON|property|position/i);
  assert.equal(fs.readFileSync(catalogFile, 'utf8'), '{invalid catalog', 'corrupt library is not reset or overwritten');
  console.log('agent app library: discovery, privacy, approval, versioning, conflicts and isolation passed');
} finally {
  for (const service of services) service.store.close?.();
  fs.rmSync(folder, { recursive: true, force: true });
}
