import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'ma-ui-artifacts-'));
try {
  const compile = createSharedCompiler(process.cwd(), temp);
  const { buildUiArtifactHtml, hasMermaidMarkup, writeUiArtifact, nextUiArtifactSeq, slugifyUiTitle, uiArtifactFileName, UI_ARTIFACT_MAX_BYTES } = await import(pathToFileURL(compile('main/uiArtifacts.ts')).href);
  assert.equal(slugifyUiTitle('回归测试结果'), 'ui');
  assert.equal(slugifyUiTitle('A/B 对比 v2!'), 'A-B-v2');
  assert.equal(uiArtifactFileName(1, 'env', 'inline'), '01-env.inline.html');
  assert.equal(uiArtifactFileName(2, '回归汇总', 'inline'), '02-ui.inline.html');
  assert.equal(uiArtifactFileName(12, 'x', 'browser'), '12-x.browser.html');
  assert.equal(nextUiArtifactSeq([]), 1);
  assert.equal(nextUiArtifactSeq(['01-a.inline.html', '03-b.browser.html', 'random.txt']), 4);
  const input = { title: '回归', html: '<ma-text>正文</ma-text>', note: '来源 <b>需转义</b>' };
  const built = buildUiArtifactHtml(input);
  assert.ok(built.html.includes('ma-ui-content') && built.html.includes('"v":2'));
  assert.ok(built.html.includes('Content-Security-Policy'));
  assert.ok(built.html.includes('<footer class="ma-note">来源 &lt;b&gt;需转义&lt;/b&gt;</footer>'));
  assert.ok(!built.html.includes('data-preset') && !built.html.includes('mountAll'), 'artifacts have no template dispatch code');
  assert.ok(built.html.includes('data-theme="dark"'));
  assert.equal(hasMermaidMarkup(input.html), false);
  const mermaid = buildUiArtifactHtml({ title: '流程图', html: '<pre class="mermaid">flowchart LR\n  A --> B</pre>' });
  assert.equal(hasMermaidMarkup('<pre class="mermaid">flowchart LR</pre>'), true);
  assert.ok(mermaid.html.includes('Pele 1.9.0') && mermaid.html.includes('ma-mermaid-rendered'), 'Mermaid artifacts include the offline session renderer');
  assert.ok(Buffer.byteLength(mermaid.html) <= UI_ARTIFACT_MAX_BYTES, 'a small Mermaid artifact fits the existing size limit');
  assert.ok(buildUiArtifactHtml(input, 'light').html.includes('data-theme="light"'));
  assert.deepEqual(built.warnings, []);
  const author = '<!--<script></script><ma-text style="color:#ff0000">x</ma-text>';
  const authored = buildUiArtifactHtml({ title: '自制', html: author });
  const island = authored.html.match(/id="ma-ui-source" type="application\/json">([\s\S]*?)<\/script>/);
  assert.ok(island && island[1].includes('\\u003c') && !island[1].includes('</script>'), 'author source cannot escape its JSON island');
  assert.equal(authored.warnings.length, 1);
  assert.ok(authored.html.indexOf('window.maUi') < authored.html.indexOf('color:#ff0000'), 'shared bridge loads before author code');
  const dir = path.join(temp, 'session', 'ui');
  const bad = await writeUiArtifact(dir, { title: '旧模板', preset: 'table', data: {} });
  assert.equal(bad.ok, false); assert.ok(bad.issues.some(issue => issue.path === 'preset'));
  assert.equal(fs.existsSync(dir), false, 'invalid input does not create an artifact directory');
  const first = await writeUiArtifact(dir, input);
  assert.equal(first.ok, true); assert.ok(first.filePath.endsWith('01-ui.inline.html'));
  const browser = await writeUiArtifact(dir, { ...input, title: '宽表 wide', mode: 'browser' });
  assert.ok(browser.filePath.endsWith('02-wide.browser.html'));
  const raceDir = path.join(temp, 'race', 'ui');
  const raced = await Promise.all(Array.from({ length: 10 }, (_, index) => writeUiArtifact(raceDir, { title: '部件 ' + index, html: '<ma-text>' + index + '</ma-text>' })));
  assert.ok(raced.every(result => result.ok));
  assert.deepEqual(raced.map(result => path.basename(result.filePath).slice(0, 2)).sort(), ['01', '02', '03', '04', '05', '06', '07', '08', '09', '10']);
  const unknown = await writeUiArtifact(dir, { ...input, unknown: true });
  assert.equal(unknown.ok, false); assert.ok(unknown.issues.some(issue => issue.path === 'unknown'));
  const warn = await writeUiArtifact(dir, { title: '字号', html: '<i style="font-size:30px">x</i>' });
  assert.equal(warn.ok, true); assert.equal(warn.warnings.length, 1);
  const big = await writeUiArtifact(dir, { title: 'big', html: '<div>' + 'x'.repeat(UI_ARTIFACT_MAX_BYTES) + '</div>' });
  assert.equal(big.ok, false); assert.match(big.error, /上限/);
  console.log('ui-artifacts: HTML generation/source isolation/notes/numbering/concurrency/validation/size passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
