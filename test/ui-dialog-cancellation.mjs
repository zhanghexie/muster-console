import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { EventEmitter } from 'node:events';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-dialog-cancel-'));
try {
  const compile = createSharedCompiler(process.cwd(), fixture);
  const entry = compile('main/uiBridge.ts');
  const electron = path.join(fixture, 'node_modules/electron'); fs.mkdirSync(electron, { recursive: true });
  fs.writeFileSync(path.join(electron, 'package.json'), '{"type":"module","exports":"./index.mjs"}');
  fs.writeFileSync(path.join(electron, 'index.mjs'), 'export const ipcMain = globalThis.dialogIpc; export const nativeImage = {}; export class Notification {}');
  const ipc = new EventEmitter(); globalThis.dialogIpc = ipc;
  const sent = [], win = new EventEmitter(), wc = new EventEmitter();
  wc.isDestroyed = () => false; wc.send = (channel, payload) => { if (payload.title === 'broken') throw Error('renderer send failed'); sent.push({ channel, payload }); };
  Object.assign(win, { webContents: wc, isDestroyed: () => false, isMinimized: () => false, isVisible: () => true, focus() {} });
  const { UiBridge } = await import(pathToFileURL(entry));
  const ui = new UiBridge(() => win, () => 'workspace');
  const first = new AbortController(), queued = new AbortController(), menu = new AbortController();
  const prompt = ui.prompt({ title: 'first' }, first.signal);
  const second = ui.select({ title: 'queued', items: [{ id: 'a', label: 'A' }] }, queued.signal);
  const third = ui.multiSelect({ title: 'third', items: [{ id: 'a', label: 'A' }] });
  const fourth = ui.menu({ title: 'menu', items: [{ id: 'a', label: 'A' }] }, menu.signal);
  queued.abort(); menu.abort();
  assert.equal(await second, null); assert.equal(await fourth, null);
  assert.equal(sent.filter(item => item.channel === 'ui:dialog').length, 1, 'queued cancellation never displays');
  const request = sent[0].payload;
  assert.equal('signal' in request, false);
  first.abort(); assert.equal(await prompt, null);
  assert.ok(sent.some(item => item.channel === 'ui:dialogClosed' && item.payload.requestId === request.requestId));
  const next = sent.filter(item => item.channel === 'ui:dialog').at(-1).payload;
  assert.equal(next.title, 'third');
  ipc.emit(`ui:dialog:${request.requestId}`, null, { cancelled: false, value: 'late' });
  ipc.emit(`ui:dialog:${next.requestId}`, null, { cancelled: false, value: ['a'] });
  assert.deepEqual(await third, ['a']);
  assert.equal(ipc.eventNames().length, 0);
  assert.equal(win.listenerCount('closed'), 0); assert.equal(wc.listenerCount('destroyed'), 0);
  const broken = ui.prompt({ title: 'broken' }); const failed = assert.rejects(broken, /renderer send failed/);
  const after = ui.prompt({ title: 'after failure' }); await failed;
  const last = sent.filter(item => item.channel === 'ui:dialog').at(-1).payload;
  assert.equal(last.title, 'after failure', 'request failure does not strand the queue');
  ipc.emit(`ui:dialog:${last.requestId}`, null, { cancelled: true }); assert.equal(await after, null);
  const before = sent.length; const aborted = new AbortController(); aborted.abort();
  assert.equal(await ui.prompt({ title: 'preaborted' }, aborted.signal), null); assert.equal(sent.length, before);
  console.log('ui-dialog-cancellation: OK (queued/active/preabort, late reply and failed-send recovery)');
} finally { delete globalThis.dialogIpc; fs.rmSync(fixture, { recursive: true, force: true }); }
