import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'muster-native-roots-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const load = f => import(pathToFileURL(compile(f)).href);
  const { userDataStorage } = await load('main/runtimeKernel/storageRootResolver.ts');
  const { GuiSessionStore } = await load('main/agentSession/persist.ts');
  const { UiWidgetStore } = await load('main/uiWidgetStore.ts');
  const { piModesDir } = await load('main/agentSession/drivers/pi/modes.ts');
  const { resolveClaudeConfigDir } = await load('shared/claudeGui.ts');
  const root = path.join(temp, 'profile'), storage = userDataStorage(root);
  new GuiSessionStore(root).beginForkPreparation('target');
  assert.equal(fs.existsSync(path.join(root, 'agent-sessions')), true);
  assert.equal(fs.existsSync(path.join(root, 'agent-fork-pending', 'target.json')), true);
  assert.equal(piModesDir(root), path.join(root, 'agents', 'pi', 'modes'));
  assert.equal(storage.resolve('app', 'pi-native-sessions'), path.join(root, 'agents', 'pi', 'sessions'));
  assert.equal(storage.resolve('app', 'pi-sessions'), path.join(root, 'pi-sessions'));
  assert.equal(storage.resolve('app', 'terminal-captures'), path.join(root, 'terminal-captures'));
  assert.equal(storage.resolve('app', 'feishu-qr'), path.join(root, 'feishu-qr'), 'phone Feishu onboarding still owns its QR workspace');
  assert.equal(storage.resolve('app', 'muster-core'), path.join(root, 'muster-core'));
  const isolated = storage.resolve('app', 'claude-gui-home');
  const options = { userDataDir: root, homedir: '/home/test', envConfigDir: '/external/config', join: path.join, isolatedConfigDir: isolated };
  assert.equal(resolveClaudeConfigDir({ ...options, isolate: true }), path.join(root, 'agents', 'claude-gui'));
  assert.equal(resolveClaudeConfigDir({ ...options, isolate: false }), '/external/config');
  assert.equal(resolveClaudeConfigDir({ ...options, envConfigDir: undefined, isolate: false }), path.join('/home/test', '.claude'));
  const old = path.join(temp, 'metaagent-workbench');
  for (const action of [() => new GuiSessionStore(old), () => piModesDir(old), () => userDataStorage(old).resolve('app', 'muster-core')]) assert.throws(action, /legacy product storage/);
  const legacyWidgetDir = path.join(old, 'agent-sessions', 'widget-session', 'ui');
  fs.mkdirSync(legacyWidgetDir, { recursive: true });
  const legacyWidget = path.join(legacyWidgetDir, '1-test.inline.html');
  fs.writeFileSync(legacyWidget, '<!doctype html><html><head></head><body>test</body></html>');
  await assert.rejects(() => new UiWidgetStore(old).read(legacyWidget), /legacy product storage/);
  fs.rmSync(old, { recursive: true, force: true });
  assert.equal(fs.existsSync(old), false);
  console.log('Native storage: GUI fork, Pi bucket separation, isolated Claude and external-home semantics passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
