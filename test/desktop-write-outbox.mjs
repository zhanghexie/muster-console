import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-outbox-'));
let store;
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { WriteOutbox } = await import(pathToFileURL(compile('main/desktop/writeOutbox.ts')));
  const file = path.join(temp, 'outbox.sqlite');
  let now = 1000;
  store = new WriteOutbox(file, () => now);
  const context = { sessionId: 'session-1', taskId: 'task-1', source: 'desktop', action: 'click', target: 'app-1' };
  const first = store.create(context);
  assert.match(first, /^[a-f0-9-]{36}$/);
  assert.equal(store.get('session-1', first).state, 'pending');
  assert.equal(store.get('other-session', first), undefined);
  assert.throws(() => store.markDispatched('other-session', first), /state/i);
  assert.throws(() => store.acknowledge('other-session', first, 'foreign'), /state/i);
  store.markDispatched('session-1', first);
  assert.throws(() => store.markDispatched('session-1', first), /state/i, 'replay must never dispatch again');
  store.close();
  store = new WriteOutbox(file, () => now);
  assert.equal(store.recover('session-1')[0].state, 'unknown', 'crash after dispatch is unknown');
  assert.throws(() => store.markDispatched('session-1', first), /state/i);
  store.settleInterrupted('session-1', first);
  assert.throws(() => store.complete('session-1', first, { outcome: 'known', value: true }), /state/i);
  assert.deepEqual(store.get('session-1', first).result, { outcome: 'unknown' });
  store.acknowledge('session-1', first, 'receipt-1');
  store.acknowledge('session-1', first, 'receipt-1');
  assert.equal(store.recover('session-1').length, 0);
  assert.equal(store.isTaskBlocked('session-1', 'task-1'), true, 'delivered unknown remains blocked');
  assert.equal(store.isTaskBlocked('other-session', 'task-1'), false);
  assert.throws(() => store.resolveUnknown('other-session', first, 'abandoned', 'audit-1'), /state/i);
  store.resolveUnknown('session-1', first, 'abandoned', 'audit-1');
  assert.equal(store.isTaskBlocked('session-1', 'task-1'), false);
  const second = store.create(context);
  store.markDispatched('session-1', second);
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: { bad: NaN } }), /result/i);
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: { bad: undefined } }), /result/i);
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: new Date() }), /result/i);
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: new Map([['x', 1]]) }), /result/i);
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: -0 }), /result/i);
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: Array(1) }), /result/i);
  store.complete('session-1', second, { outcome: 'known', value: { ok: true } });
  store.complete('session-1', second, { outcome: 'known', value: { ok: true } });
  assert.throws(() => store.complete('session-1', second, { outcome: 'known', value: { ok: false } }), /state/i);
  assert.throws(() => store.acknowledge('session-1', second, 'receipt-1'), /receipt/i, 'receipt IDs cannot be reused');
  assert.deepEqual(store.get('session-1', second).result, { outcome: 'known', value: { ok: true } });
  store.acknowledge('session-1', second, 'receipt-2');
  const pending = store.create(context);
  assert.equal(store.recover('session-1')[0].state, 'unknown');
  assert.equal(store.isTaskBlocked('session-1', 'task-1'), true);
  assert.equal(store.recover('other-session').length, 0);
  assert.throws(() => store.recover('session-1', 0, 501), /cursor/i);
  store.settleInterrupted('session-1', pending);
  assert.throws(() => store.markDispatched('session-1', pending), /state/i);
  now += 24 * 60 * 60 * 1000 - 1;
  assert.equal(store.prune(), 0);
  now += 1;
  assert.equal(store.prune(), 2);
  assert.equal(store.get('session-1', second), undefined);
  assert.equal(store.recover('session-1').length, 1, 'undelivered records are never pruned');
  store.acknowledge('session-1', pending, 'receipt-3');
  now += 24 * 60 * 60 * 1000;
  assert.equal(store.prune(), 0, 'delivered but unresolved unknown must survive retention');
  assert.equal(store.isTaskBlocked('session-1', 'task-1'), true);
  store.resolveUnknown('session-1', pending, 'confirmed-not-applied', 'audit-2');
  assert.equal(store.prune(), 1);
  const corrupt = store.create(context);
  store.markDispatched('session-1', corrupt);
  store.complete('session-1', corrupt, { outcome: 'known', value: true });
  store.acknowledge('session-1', corrupt, 'receipt-4');
  const db = new DatabaseSync(file);
  db.prepare('UPDATE write_outbox SET result = ? WHERE id = ?').run('not-json', corrupt);
  db.close();
  now += 24 * 60 * 60 * 1000;
  assert.equal(store.prune(), 0, 'corrupt records cannot be cleaned up as successful');
  assert.throws(() => store.isTaskBlocked('session-1', 'task-1'), /JSON|outbox/i);
  console.log('write outbox: crash recovery, scoped replay, acknowledgements and retention');
} finally {
  store?.close();
  const resolved = fs.realpathSync(temp);
  assert.equal(path.dirname(resolved), fs.realpathSync(os.tmpdir()));
  assert.ok(path.basename(resolved).startsWith('desktop-outbox-'));
  fs.rmSync(resolved, { recursive: true, force: true, maxRetries: 5 });
}
