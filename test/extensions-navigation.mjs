import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { acquireTestLease } from './helpers/lease.mjs';

const root = path.resolve(import.meta.dirname, '..');
const release = acquireTestLease(root);
try {
  const ts = createRequire(import.meta.url)('typescript');
  const source = path.join(root, 'src/shared/extensionNavigation.ts');
  const out = path.join(root, '.tmp/extension-navigation-tests.mjs');
  const iconsSource = path.join(root, 'src/shared/extensionIcons.ts');
  const iconsOut = path.join(root, '.tmp/extensionIcons');
  fs.writeFileSync(iconsOut, ts.transpileModule(fs.readFileSync(iconsSource, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText);
  fs.writeFileSync(out, ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText);
  const { moveNavigation, canMoveNavigation, dissolveNavigationFolder, navigationChildren, parseNavigation, normalizeNavigationUrl, visibleNavigation } = await import(pathToFileURL(out).href);
  const folder = (id, parentId = null) => ({ id, title: id, parentId, kind: 'folder', expanded: true });
  const web = (id, parentId = null) => ({ id, title: id, parentId, kind: 'web', url: 'https://example.com/' });
  const nodes = [folder('a'), web('one', 'a'), folder('nested', 'a'), web('two', 'nested'), folder('b'), web('three')];
  assert.equal(canMoveNavigation(nodes, { sourceId: 'a', targetId: 'nested', placement: 'inside' }), false);
  assert.equal(canMoveNavigation(nodes, { sourceId: 'a', targetId: 'two', placement: 'before' }), false);
  assert.equal(canMoveNavigation(nodes, { sourceId: 'a', targetId: 'a', placement: 'after' }), false);
  assert.equal(canMoveNavigation(nodes, { sourceId: 'one', targetId: 'three', placement: 'inside' }), false);
  assert.equal(moveNavigation(nodes, { sourceId: 'a', targetId: 'nested', placement: 'inside' }), nodes);
  let next = moveNavigation(nodes, { sourceId: 'b', targetId: 'a', placement: 'before' });
  assert.deepEqual(navigationChildren(next, null).map(node => node.id), ['b', 'a', 'three']);
  assert.equal(next.find(node => node.id === 'two').parentId, 'nested');
  next = moveNavigation(nodes.map(node => node.id === 'b' ? { ...node, expanded: false } : node), { sourceId: 'one', targetId: 'b', placement: 'inside' });
  assert.equal(next.find(node => node.id === 'one').parentId, 'b');
  assert.equal(next.find(node => node.id === 'b').expanded, true);
  next = moveNavigation(nodes, { sourceId: 'one', targetId: null, placement: 'inside' });
  assert.deepEqual(navigationChildren(next, null).map(node => node.id), ['a', 'b', 'three', 'one']);
  next = dissolveNavigationFolder(nodes, 'a');
  assert.deepEqual(navigationChildren(next, null).map(node => node.id), ['one', 'nested', 'b', 'three']);
  assert.equal(next.find(node => node.id === 'two').parentId, 'nested');
  assert.equal(nodes[1].parentId, 'a', 'operations leave input untouched for undo');
  assert.deepEqual(visibleNavigation(nodes.map(node => node.id === 'a' ? { ...node, expanded: false } : node)).map(row => row.node.id), ['a', 'b', 'three']);
  assert.equal(parseNavigation([folder('a', 'b'), folder('b', 'a')]), null);
  assert.equal(parseNavigation([web('a', 'missing')]), null);
  assert.equal(parseNavigation([web('a'), web('a')]), null);
  assert.equal(normalizeNavigationUrl('javascript:alert(1)'), null);
  assert.equal(normalizeNavigationUrl('https://user:secret@example.com'), null);
  assert.equal(normalizeNavigationUrl('localhost:8188'), 'http://localhost:8188/');
  assert.equal(normalizeNavigationUrl('example.com'), 'https://example.com/');
  assert.equal(parseNavigation([{ ...web('a'), url: 'example.com' }])[0].url, 'https://example.com/');
  assert.equal(parseNavigation(nodes).length, nodes.length);
  assert.equal(parseNavigation([{ ...web('a'), favorite: true }])[0].favorite, true);
  assert.equal(parseNavigation([{ ...web('a'), favorite: 'true' }]), null);
  assert.equal(parseNavigation([web('a')])[0].favorite, undefined, 'previous saved prototypes remain compatible');
  assert.equal(parseNavigation([{ id: 'bad-icon', title: 'Bad', parentId: null, kind: 'extension', extensionId: 'demo', viewId: 'main', icon: 'builtin-extension:missing' }]), null);
  const scoped = moveNavigation([{ ...web('w'), scope: 'global' }, folder('legacy')], { sourceId: 'w', targetId: 'legacy', placement: 'inside' });
  assert.equal(scoped.find(node => node.id === 'w').scope, 'workspace', 'legacy folders use workspace scope when moving a global node');
  assert.equal(parseNavigation([{ id: 'tab', title: 'Tab', parentId: null, kind: 'extension', extensionId: 'demo', viewId: 'panel', placement: 'tab' }])[0].placement, 'tab');
  console.log('extensions-navigation: 27 assertions passed (moves, cycle guards, dissolve, visibility, URL, favorites and persistence).');
} finally { release(); }
