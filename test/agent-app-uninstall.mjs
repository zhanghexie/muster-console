import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { buildSync } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const tempRoot = fs.realpathSync(os.tmpdir());
const folder = fs.mkdtempSync(path.join(tempRoot, 'agent-app-uninstall-'));
if (path.dirname(fs.realpathSync(folder)) !== tempRoot) throw new Error('Unexpected test directory');
const services = [];
try {
  const bundle = path.join(folder, 'service.cjs');
  buildSync({ stdin: { contents: "export { AgentAppsService } from './src/main/agentApps/service'; export { defineRecordApp } from './src/shared/agentApps'; export { agentAppsHost } from './src/main/capabilities/hosts/agentApps'; export { runAsAgentWorkspace, runAsSchedulerTool } from './src/main/agent/agentScope';", resolveDir: root, sourcefile: 'uninstall-fixture.ts' }, outfile: bundle, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  const { AgentAppsService, defineRecordApp, agentAppsHost, runAsAgentWorkspace, runAsSchedulerTool } = createRequire(import.meta.url)(bundle);
  const createService = options => { const service = new AgentAppsService(options); services.push(service); return service; };
  const options = { root: path.join(folder, 'data'), workspaces: () => ['one', 'two'], emit() {}, encrypt: x => x, decrypt: x => x, confirmSend: async () => true, authorizeDefinition: async () => true, deliver: async () => ({ muted: true }), connectors: { feed: async () => [], sync: async () => ({ records: [], cursor: {} }), send: async () => ({ messageId: 'unused' }), test: async () => {} } };
  let service = createService(options);
  const app = defineRecordApp({ id: 'notes', name: 'Notes', fields: [{ id: 'title', label: 'Title', type: 'text', required: true }], titleField: 'title' });
  app.permissions = ['mail.read'];
  await service.install('one', app);
  await service.install('two', app);
  const actor = { kind: 'human', runId: 'test' };
  const create = ws => service.execute(ws, { appId: 'notes', commandId: 'create', params: { values: { title: `record-${ws}` } } }, actor);
  const oneRecord = (await create('one')).record;
  const twoRecord = (await create('two')).record;
  await service.execute('one', { appId: 'reminders', commandId: 'set', params: { values: { title: 'follow up', dueAt: new Date(Date.now() + 60_000).toISOString(), targetApp: 'notes', targetId: oneRecord.id } } }, actor);
  service.store.transact('one', state => {
    state.connections.push({ kind: 'imap-smtp', id: 'shared', name: 'Shared', address: 'a@example.com', user: 'a', imapHost: 'imap.example.com', imapPort: 993, imapTls: 'tls', smtpHost: 'smtp.example.com', smtpPort: 465, smtpTls: 'tls', mailbox: 'INBOX', enabled: true, grants: { mail: ['mail.read'], notes: ['mail.read'] }, revision: 1 });
    state.receipts.push({ key: 'notes:send', fingerprint: 'same', state: 'uncertain', external: true, at: Date.now(), result: { record: oneRecord } });
    state.outbox.push({ id: 'pending-notice', appId: 'notes', kind: 'custom.new', recordIds: [oneRecord.id], title: 'private', createdAt: Date.now(), attempts: 0, nextAttemptAt: 0, action: 'wake' });
  });
  assert.throws(() => service.uninstall('one', 'tasks'), /built.in/i);
  const invoke = args => runAsAgentWorkspace('one', () => runAsSchedulerTool(() => agentAppsHost['apps.run']({ agentApps: service }, args)));
  const noticeStarted = Promise.withResolvers();
  const noticeReceipt = Promise.withResolvers();
  options.deliver = () => { noticeStarted.resolve(); return noticeReceipt.promise; };
  const pendingTick = service.tick();
  await Promise.race([noticeStarted.promise, pendingTick.then(() => assert.fail('notification was never submitted'))]);
  const result = await invoke({ action: 'uninstall', appId: 'notes' });
  noticeReceipt.resolve({ messageId: 'notice-submitted' });
  await pendingTick;
  assert.equal(result.dataDeleted, false);
  assert.equal(service.snapshot('one').apps.some(item => item.definition.id === 'notes'), false);
  let state = service.store.read('one');
  assert.equal(state.records.notes[0].id, oneRecord.id);
  assert.equal(state.outbox.find(event => event.id === 'pending-notice').action, 'mute', 'in-flight notifications must remain invalidated until their receipt settles');
  assert.equal(state.jobs.find(job => job.params.targetApp === 'notes').enabled, false);
  assert.deepEqual(state.connections[0].grants, { mail: ['mail.read'] });
  assert.equal(service.query('two', { appId: 'notes' }).record, undefined);
  assert.equal(service.query('two', { appId: 'notes' }).records[0].id, twoRecord.id);
  service = createService(options);
  await assert.rejects(service.install('one', { ...app, name: 'Different app' }), /retained data|identity/i);
  await service.install('one', app);
  assert.equal(service.query('one', { appId: 'notes' }).records[0].id, oneRecord.id);
  assert.equal(service.store.read('one').connections[0].grants.notes, undefined, 'reinstall cannot silently restore a connection grant');
  await invoke({ action: 'uninstall', appId: 'notes', params: { deleteData: true } });
  state = service.store.read('one');
  assert.equal(state.records.notes, undefined);
  assert.equal(state.connections[0].id, 'shared');
  assert.equal(state.receipts.find(receipt => receipt.key === 'notes:send').state, 'uncertain');
  assert.ok(!JSON.stringify(state.receipts).includes('record-one'), 'retained send receipts cannot retain deleted record content');
  assert.equal(service.query('two', { appId: 'notes' }).records[0].id, twoRecord.id);
  console.log('agent app uninstall: workspace scope, retention, identity, grants and deletion passed');
} finally {
  for (const service of services) service.store.close?.();
  fs.rmSync(folder, { recursive: true, force: true });
}
