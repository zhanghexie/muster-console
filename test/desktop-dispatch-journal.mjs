import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-journal-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const moduleUrl = pathToFileURL(compile('main/desktop/dispatchJournal.ts')).href;
  const { DesktopDispatchJournal } = await import(moduleUrl);
  const dir = path.join(temp, 'journal'), journal = new DesktopDispatchJournal(dir);
  const input = { appId: 'app', surfaceId: 'window', action: 'click', objectFingerprint: 'a'.repeat(64) };
  assert.equal(await journal.read('../task'), null);
  const [first, second] = await Promise.allSettled([journal.begin('../task', input), journal.begin('../task', input)]);
  assert.equal([first, second].filter(result => result.status === 'fulfilled').length, 1);
  const written = first.status === 'fulfilled' ? first.value : second.value;
  const files = fs.readdirSync(dir); assert.equal(files.length, 1); assert.match(files[0], /^[0-9a-f]{64}\.json$/);
  const restarted = new DesktopDispatchJournal(dir);
  assert.deepEqual(await restarted.read('../task'), written);
  await assert.rejects(restarted.finish('../task', 'wrong-id'), /changed/);
  assert.deepEqual(await journal.read('../task'), written);
  await restarted.finish('../task', written.id);
  assert.equal(await journal.read('../task'), null);
  const childCode = `import { DesktopDispatchJournal } from ${JSON.stringify(moduleUrl)};
    const journal = new DesktopDispatchJournal(process.argv[1]);
    await journal.begin('crashed-task', { appId: 'app', surfaceId: 'window', action: 'click' });
    await journal.recordRefusal('crashed-task', 'refused-scope');
    process.exit(0);`;
  execFileSync(process.execPath, ['--input-type=module', '-e', childCode, dir], { stdio: 'pipe' });
  const afterExit = await restarted.read('crashed-task'); assert.equal(afterExit?.action, 'click');
  assert.equal(await restarted.hasRefusal('crashed-task', 'refused-scope'), true);
  await restarted.clearRefusal('crashed-task', 'refused-scope');
  await restarted.finish('crashed-task', afterExit.id);
  await journal.recordRefusal('task', 'scope');
  assert.equal(await restarted.hasRefusal('task', 'scope'), true);
  assert.equal(await restarted.hasRefusal('other', 'scope'), false);
  await restarted.clearRefusal('task', 'scope');
  assert.equal(await journal.hasRefusal('task', 'scope'), false);
  const corrupt = await journal.begin('bad', input);
  const marker = fs.readdirSync(dir).find(name => name.endsWith('.json')); fs.writeFileSync(path.join(dir, marker), '{');
  await assert.rejects(journal.read('bad'), /manual recovery/);
  await assert.rejects(journal.finish('bad', corrupt.id), /manual recovery/);
  await assert.rejects(journal.begin('bad', input));
  await assert.rejects(journal.begin('other', { ...input, objectFingerprint: 'raw secret' }), /Invalid/);
  const link = path.join(temp, 'linked'); fs.symlinkSync(dir, link, process.platform === 'win32' ? 'junction' : 'dir');
  await assert.rejects(new DesktopDispatchJournal(link).read('task'), /Invalid desktop journal directory/);
  console.log('desktop journal: exclusive markers, crash recovery, corruption and identity checks passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
