import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const root = process.cwd(), temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-epoch-'));
let history, reusedHistory, failedHistory;
try {
  const compile = createSharedCompiler(root, temp);
  const { SchedulerDesktopTaskEpochs } = await import(pathToFileURL(compile('main/desktop/schedulerTaskEpoch.ts')));
  const { SqliteDesktopEpochHistory } = await import(pathToFileURL(compile('main/desktop/epochHistory.ts')));
  const { MAX_DESKTOP_GRANT_TTL_MS } = await import(pathToFileURL(compile('main/desktop/grants.ts')));
  const legacyFile = path.join(temp, 'legacy.sqlite'), legacyDb = new DatabaseSync(legacyFile);
  legacyDb.exec(`CREATE TABLE desktop_epoch_sessions (session_id TEXT PRIMARY KEY, generation INTEGER NOT NULL);
    CREATE TABLE desktop_epoch_history (session_id TEXT NOT NULL, generation INTEGER NOT NULL, task_id TEXT NOT NULL UNIQUE, PRIMARY KEY(session_id, generation, task_id));
    INSERT INTO desktop_epoch_sessions VALUES ('legacy', 0); INSERT INTO desktop_epoch_history VALUES ('legacy', 0, 'legacy-task');`);
  legacyDb.close();
  const migrated = new SqliteDesktopEpochHistory(legacyFile);
  assert.equal(migrated.findByHash('legacy', 0, createHash('sha256').update('legacy-task').digest('hex')), 'legacy-task');
  migrated.close();
  const historyFile = path.join(temp, 'epochs.sqlite'); history = new SqliteDesktopEpochHistory(historyFile);
  let now = 10, next = 0, resolvePending;
  const prompts = [], audits = [];
  const epochs = new SchedulerDesktopTaskEpochs(async request => {
    prompts.push(request);
    if (request.appId === 'pending') return new Promise(resolve => { resolvePending = resolve; });
    if (request.appId === 'denied') return {};
    return { approvalId: `host-confirm-${++next}` };
  }, async (session, request, result) => { audits.push({ session, request, result }); }, history, () => now);
  const scope = { appId: 'app-a', actionClass: 'click' }, current = () => true;
  const task1 = await epochs.ensure('scheduler', scope, current);
  assert.equal(task1, 'host-confirm-1');
  assert.deepEqual(epochs.currentBinding('scheduler'), { epoch: task1, anchor: task1, generation: 0 });
  assert.deepEqual(prompts[0], { kind: 'start', ...scope });
  assert.equal(await epochs.ensure('scheduler', scope, current), task1);
  assert.equal(prompts.length, 1);
  assert.equal(await epochs.extend('scheduler', { appId: 'app-b', actionClass: 'type' }, current), task1);
  assert.deepEqual(prompts[1], { kind: 'extend', taskId: task1, appId: 'app-b', actionClass: 'type' });
  const task2 = await epochs.startNew('scheduler', scope, current);
  assert.notEqual(task1, task2);
  assert.equal(epochs.isCurrent('scheduler', task1), false);
  assert.equal(epochs.isCurrent('scheduler', task2), true);
  assert.equal(epochs.ownsArtifact('scheduler', task1), true);
  assert.equal(epochs.ownsArtifact('another', task1), false);
  const reopened = new SqliteDesktopEpochHistory(historyFile);
  const restarted = new SchedulerDesktopTaskEpochs(async () => ({}), async () => {}, reopened, () => now);
  assert.equal(restarted.ownsArtifact('scheduler', task1), true, 'same session retains old artifact ownership after restart');
  assert.equal(restarted.isCurrent('scheduler', task2), false, 'restart never silently restores active authorization');
  assert.equal(reopened.owns('scheduler', reopened.generation('scheduler'), task1), true, 'prior task ownership survives database reopen');
  assert.throws(() => reopened.record('another', reopened.generation('another'), task1), /UNIQUE/, 'a receipt cannot be reused by a different session');
  reopened.close();
  await assert.rejects(epochs.startNew('scheduler', { ...scope, appId: 'denied' }, current), /declined/);
  assert.equal(epochs.isCurrent('scheduler', task2), true);
  now += MAX_DESKTOP_GRANT_TTL_MS;
  assert.equal(epochs.isCurrent('scheduler', task2), false);
  assert.equal(epochs.currentBinding('scheduler'), null, 'expired epoch is not captured by new waits');
  assert.equal(epochs.ownsArtifact('scheduler', task2), true);
  await assert.rejects(epochs.extend('scheduler', scope, current), /No active/);
  const pending = epochs.ensure('scheduler', { ...scope, appId: 'pending' }, current);
  await new Promise(resolve => setImmediate(resolve));
  const oldGeneration = history.generation('scheduler');
  epochs.closeSession('scheduler');
  resolvePending({ approvalId: 'late' });
  await assert.rejects(pending, /caller changed/);
  assert.equal(epochs.ownsArtifact('scheduler', task1), false);
  assert.throws(() => history.record('scheduler', oldGeneration, 'late-receipt'), /generation changed/);
  assert.equal(audits.at(-1).result, 'denied');
  reusedHistory = new SqliteDesktopEpochHistory(':memory:');
  const reused = new SchedulerDesktopTaskEpochs(async () => ({ approvalId: 'same-id' }), async () => {}, reusedHistory, () => now);
  await reused.ensure('one', scope, current);
  await assert.rejects(reused.ensure('two', scope, current), /already used/);
  failedHistory = new SqliteDesktopEpochHistory(':memory:');
  const failedAudit = new SchedulerDesktopTaskEpochs(async () => ({ approvalId: 'audit-id' }), async () => { throw new Error('audit failed'); }, failedHistory, () => now);
  await assert.rejects(failedAudit.ensure('one', scope, current), /audit failed/);
  assert.equal(failedAudit.ownsArtifact('one', 'audit-id'), false);
  const unavailable = { generation: () => 0, record: () => { throw new Error('history unavailable'); }, owns: () => false, findByHash: () => undefined, endSession: () => {} };
  const failedStorage = new SchedulerDesktopTaskEpochs(async () => ({ approvalId: 'receipt' }), async () => {}, unavailable, () => now);
  await assert.rejects(failedStorage.ensure('one', scope, current), /history unavailable/);
  assert.equal(failedStorage.isCurrent('one', 'receipt'), false, 'missing durable ownership never grants an action');
  let unavailableNow = false;
  const intermittent = { generation: session => { if (unavailableNow) throw Error('epoch history unavailable'); return history.generation(session); },
    record: (...args) => history.record(...args), owns: (...args) => history.owns(...args), findByHash: (...args) => history.findByHash(...args),
    endSession: (...args) => history.endSession(...args) };
  const intermittentEpochs = new SchedulerDesktopTaskEpochs(async () => ({ approvalId: 'intermittent-receipt' }), async () => {}, intermittent, () => now);
  await intermittentEpochs.ensure('intermittent', scope, current);
  unavailableNow = true;
  assert.throws(() => intermittentEpochs.currentBinding('intermittent'), /history unavailable/, 'unavailable storage is not reported as no epoch');
  const failingClose = { generation: () => 0, record: () => {}, owns: () => true, findByHash: () => 'closed-task', endSession: () => { throw new Error('close failed'); } };
  const failedClose = new SchedulerDesktopTaskEpochs(async () => ({ approvalId: 'closed-task' }), async () => {}, failingClose, () => now);
  await failedClose.ensure('one', scope, current);
  assert.throws(() => failedClose.closeSession('one'), /close failed/);
  assert.equal(failedClose.ownsArtifact('one', 'closed-task'), false, 'failed persistence cannot revive historical read access in this process');
  await assert.rejects(failedClose.ensure('one', scope, current), /closing/);
  const cancelled = new AbortController(); cancelled.abort();
  await assert.rejects(epochs.ensure('other', scope, current, cancelled.signal), { name: 'AbortError' });
  const parallelTask = await epochs.ensure('parallel', scope, current);
  const external = new SqliteDesktopEpochHistory(historyFile);
  external.endSession('parallel'); external.close();
  assert.equal(epochs.isCurrent('parallel', parallelTask), false, 'external session close invalidates the live authorization');
  assert.equal(epochs.ownsArtifact('parallel', parallelTask), false);
  assert.notEqual(await epochs.ensure('parallel', scope, current), parallelTask);
  console.log('desktop task epochs: host receipt, expansion, replacement, expiry and close races passed');
} finally {
  history?.close(); reusedHistory?.close(); failedHistory?.close();
  const resolved = fs.realpathSync(temp);
  assert.equal(path.dirname(resolved), fs.realpathSync(os.tmpdir()));
  assert.ok(path.basename(resolved).startsWith('desktop-epoch-'));
  fs.rmSync(resolved, { recursive: true, force: true, maxRetries: 5 });
}
