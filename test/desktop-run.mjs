import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
import { removeWorkspaceFixture } from './helpers/workspace-fixture.mjs';

fs.mkdirSync('.tmp', { recursive: true });
const temp = fs.mkdtempSync(path.resolve('.tmp', 'desktop-run-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { DesktopRun, DesktopRunRegistry } = await import(pathToFileURL(compile('main/desktop/desktopRun.ts')));
  const events = [];
  const run = new DesktopRun(state => events.push(state));
  const finish = run.begin();
  run.stop();
  assert.equal(run.signal.aborted, true);
  assert.equal(run.status, 'stopping', 'a backend that has not returned keeps the run stopping');
  assert.throws(() => run.begin(), /stopped/);
  finish();
  finish();
  assert.equal(run.status, 'stopped');
  assert.deepEqual(events, ['active', 'stopping', 'stopped']);
  const idle = new DesktopRun(() => {});
  idle.stop();
  assert.equal(idle.status, 'stopped', 'stop works between tool calls');
  assert.throws(() => idle.begin(), /stopped/);
  const finishing = new DesktopRun(() => {});
  const finishLease = finishing.begin();
  finishing.finish();
  assert.equal(finishing.status, 'finishing');
  assert.throws(() => finishing.begin(), /stopped/);
  finishLease();
  assert.equal(finishing.status, 'stopped');
  const brokenUi = new DesktopRun(state => { if (state === 'stopping') throw new Error('UI failed'); });
  const endBroken = brokenUi.begin();
  assert.throws(() => brokenUi.stop(), /UI failed/);
  assert.equal(brokenUi.signal.aborted, true, 'notification failure must not prevent cancellation');
  endBroken();
  assert.equal(brokenUi.status, 'stopped');
  const registry = new DesktopRunRegistry(() => {});
  const a = registry.start('a');
  const b = registry.start('b');
  const doneA = a.begin();
  assert.throws(() => registry.start('a'), /still active/);
  registry.stopAll();
  assert.equal(a.signal.aborted, true);
  assert.equal(b.status, 'stopped');
  assert.throws(() => registry.start('a'), /still active/, 'must wait for in-flight backend');
  doneA();
  assert.notEqual(registry.start('a'), a, 'only explicit host start creates a new run');
  console.log('desktop run: stop latch and in-flight completion passed');
} finally { removeWorkspaceFixture(temp, 'desktop-run-'); }
