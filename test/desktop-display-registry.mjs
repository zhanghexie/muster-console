import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-display-registry-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const { ElectronDisplayRegistry } = await import(pathToFileURL(compile('main/desktop/displayRegistry.ts')));
  const provider = new EventEmitter(), power = new EventEmitter();
  const one = { id: 12, label: 'Monitor', bounds: { x: -800, y: 0, width: 800, height: 600 }, scaleFactor: 1.5, rotation: 0 };
  let rows = [one];
  provider.getAllDisplays = () => rows;
  assert.throws(() => new ElectronDisplayRegistry(provider), /power monitoring is required/);
  const registry = new ElectronDisplayRegistry(provider, power);
  const first = registry.refresh().surfaces[0], target = registry.captureTarget('task', first.surfaceId);
  assert.equal('nativeId' in first, false);
  assert.equal(target.displayId, 12);
  assert.equal(registry.isCurrent(target), true);
  first.bounds.x = 999;
  assert.equal(registry.refresh().surfaces[0].bounds.x, -800, 'public metadata cannot mutate the registry');
  provider.emit('display-metrics-changed', {}, one, ['bounds']);
  assert.equal(registry.isCurrent(target), false, 'metrics event invalidates prior captures even if values look unchanged');
  const afterMetrics = registry.refresh().surfaces[0];
  assert.equal(afterMetrics.surfaceId, target.surfaceId);
  assert.notEqual(afterMetrics.geometryRevision, target.geometryRevision);
  const beforeMove = registry.captureTarget('task', afterMetrics.surfaceId);
  rows = [{ ...one, bounds: { ...one.bounds, x: -801 } }];
  assert.equal(registry.isCurrent(beforeMove), false, 'missed geometry event is caught by live enumeration');
  const beforeReuse = registry.refresh().surfaces[0];
  const beforeResume = registry.captureTarget('task', beforeReuse.surfaceId);
  power.emit('suspend');
  assert.equal(registry.isCurrent(beforeResume), false, 'suspend invalidates all old targets');
  assert.throws(() => registry.refresh(), /suspended/, 'do not create identities while suspended');
  power.emit('resume');
  assert.equal(registry.isCurrent(beforeResume), false, 'resume cannot revive an old identity');
  provider.getAllDisplays = () => { power.emit('suspend'); power.emit('resume'); return rows; };
  assert.throws(() => registry.refresh(), /power state changed/, 'power transitions during enumeration cannot revive a target');
  provider.getAllDisplays = () => rows;
  const afterResume = registry.refresh().surfaces[0];
  const otherMissedInterval = registry.captureTarget('task', afterResume.surfaceId);
  registry.invalidateAll();
  assert.equal(registry.isCurrent(otherMissedInterval), false, 'another missed-event interval invalidates identities');
  const beforeUnplug = registry.refresh().surfaces[0];
  provider.emit('display-removed', {}, one);
  provider.emit('display-added', {}, one);
  const afterReuse = registry.refresh().surfaces[0];
  assert.notEqual(afterReuse.surfaceId, beforeUnplug.surfaceId, 'unplug and reused native ID get a new identity');
  assert.throws(() => registry.captureTarget('task', beforeUnplug.surfaceId), /no longer available/);
  rows = [one, { ...one, id: -1 }, { ...one, id: -10 }];
  assert.equal(registry.refresh().omitted, 2);
  rows = [one, one];
  assert.throws(() => registry.refresh(), /Duplicate/);
  rows = [one];
  assert.notEqual(registry.refresh().surfaces[0].surfaceId, afterReuse.surfaceId, 'failed enumeration invalidates cached identity');
  rows = [{ ...one, rotation: 45 }];
  assert.throws(() => registry.refresh(), /Invalid/);
  rows = [one];
  const last = registry.captureTarget('task', registry.refresh().surfaces[0].surfaceId);
  registry.dispose(); registry.dispose();
  assert.equal(provider.listenerCount('display-added'), 0);
  assert.equal(power.listenerCount('suspend'), 0);
  assert.equal(power.listenerCount('resume'), 0);
  assert.equal(registry.isCurrent(last), false);
  assert.throws(() => registry.refresh(), /closed/);
  console.log('display registry: event invalidation, ID reuse, live geometry and disposal passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
