import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { buildSync } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..'), require = createRequire(import.meta.url), sharp = require('sharp');
const temp = fs.realpathSync(os.tmpdir()), folder = fs.mkdtempSync(path.join(temp, 'agent-app-images-'));
if (path.dirname(fs.realpathSync(folder)) !== temp) throw new Error('Unexpected fixture directory');
let service;
try {
  const bundle = path.join(folder, 'test.cjs');
  buildSync({ stdin: { contents: "export { AgentAppsService } from './src/main/agentApps/service'; export { AgentAppsSqliteStateStore } from './src/main/agentApps/sqliteStateStore'; export { AppImageAssets } from './src/main/agentApps/images'; export { defineRecordApp } from './src/shared/agentApps';", resolveDir: root }, outfile: bundle, bundle: true, platform: 'node', format: 'cjs', packages: 'external', banner: { js: `var require=require('node:module').createRequire(${JSON.stringify(path.join(root, 'package.json'))});` }, logLevel: 'silent' });
  const { AgentAppsService, AgentAppsSqliteStateStore, AppImageAssets, defineRecordApp } = require(bundle);
  const options = { root: path.join(folder, 'agent-apps'), storeFactory: (dir, seed) => new AgentAppsSqliteStateStore(dir, seed), workspaces: () => ['one', 'two'], emit() {}, encrypt: x => x, decrypt: x => x, confirmSend: async () => true, authorizeDefinition: async () => true, deliver: async () => ({ muted: true }), connectors: { feed: async () => [], sync: async () => ({ records: [], cursor: {} }), send: async () => ({ messageId: 'fake' }), test: async () => {} } };
  service = new AgentAppsService(options);
  const definition = id => defineRecordApp({ id, name: id, fields: [{ id: 'title', label: 'Title', type: 'text', required: true }, { id: 'image', label: 'Image', type: 'image', required: true }], titleField: 'title' });
  await service.install('one', definition('photos'));
  await service.install('one', definition('other'));
  await service.install('two', definition('photos'));
  const images = new AppImageAssets(path.join(folder, 'assets'), service.store);
  const source = path.join(folder, 'fixture.jpg');
  const original = await sharp({ create: { width: 640, height: 320, channels: 3, background: '#3388aa' } }).jpeg().withMetadata().toBuffer();
  fs.writeFileSync(source, original);
  const asset = await images.importFile('one', 'photos', source);
  assert.equal(asset.width, 640); assert.equal(asset.height, 320); assert.equal(asset.mime, 'image/jpeg');
  assert.deepEqual(fs.readFileSync(source), original, 'import never changes the chosen original');
  const thumb = await images.read('one', 'photos', asset.id, true);
  const metadata = await sharp(thumb.bytes).metadata();
  assert.equal(thumb.mime, 'image/png'); assert.equal(metadata.width, 256); assert.equal(metadata.height, 128); assert.equal(metadata.exif, undefined);
  assert.deepEqual(Buffer.from((await images.read('one', 'photos', asset.id)).bytes), original);
  await assert.rejects(images.read('two', 'photos', asset.id), /unavailable/);
  await assert.rejects(images.read('one', 'other', asset.id), /unavailable/);
  await assert.rejects(images.read('one', 'photos', '../secret'), /identity/);
  const actor = { kind: 'human', runId: 'test' };
  const create = (appId, title, image) => service.execute('one', { appId, commandId: 'create', params: { values: { title, image } } }, actor);
  await assert.rejects(create('other', 'Cross-app', asset.id), /unavailable/);
  const first = (await create('photos', 'First', asset.id)).record, second = (await create('photos', 'Second', asset.id)).record;
  assert.equal(service.store.imageReferenceCount('one', asset.id), 2);
  const remove = record => service.execute('one', { appId: 'photos', commandId: 'remove', params: { id: record.id, expectedRevision: record.revision } }, actor);
  await remove(first);
  assert.equal(await images.removeIfUnused('one', 'photos', asset.id), false, 'another record still owns a reference');
  await remove(second);
  const [activeRead, removed] = await Promise.all([images.read('one', 'photos', asset.id), images.removeIfUnused('one', 'photos', asset.id)]);
  assert.deepEqual(Buffer.from(activeRead.bytes), original, 'deletion waits for an active read');
  assert.equal(removed, true);
  await assert.rejects(images.read('one', 'photos', asset.id), /unavailable/);
  const interrupted = await images.importFile('one', 'photos', source);
  service.store.changeImageAsset('one', { type: 'markImageDeleting', appId: 'photos', id: interrupted.id });
  await assert.rejects(create('photos', 'Deleting', interrupted.id), /unavailable/);
  await images.recover('one');
  assert.equal(service.store.imageAsset('one', 'photos', interrupted.id), undefined, 'an interrupted deletion is retried after restart');
  const unsupported = path.join(folder, 'not-an-image.svg'); fs.writeFileSync(unsupported, '<svg xmlns="http://www.w3.org/2000/svg"></svg>');
  await assert.rejects(images.importFile('one', 'photos', unsupported), /supported|image|input/i);
  const oversized = path.join(folder, 'oversized.png'); fs.writeFileSync(oversized, 'x'); fs.truncateSync(oversized, 26 * 1024 * 1024);
  await assert.rejects(images.importFile('one', 'photos', oversized), /25 MB/);
  let checks = 0;
  await assert.rejects(images.importFile('one', 'photos', source, () => { if (++checks === 3) throw new Error('app removed'); }), /app removed/);
  assert.equal(service.store.imageAssets('one', 'photos').length, 0, 'an app removed during import never commits an image');
  console.log('agent app images: formats, thumbnails, scope, references and safe deletion passed');
} finally { service?.store.close?.(); fs.rmSync(folder, { recursive: true, force: true }); }
