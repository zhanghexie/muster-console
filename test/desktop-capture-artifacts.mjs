import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { createSharedCompiler } from './helpers/shared-compile.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'desktop-capture-'));
try {
  const compile = createSharedCompiler(process.cwd(), path.join(temp, 'compiled'));
  const sharpDir = path.join(temp, 'compiled/node_modules/sharp'); fs.mkdirSync(sharpDir, { recursive: true });
  const sharpPath = createRequire(import.meta.url).resolve('sharp');
  fs.writeFileSync(path.join(sharpDir, 'package.json'), JSON.stringify({ name: 'sharp', main: 'index.cjs' }));
  fs.writeFileSync(path.join(sharpDir, 'index.cjs'), `module.exports = require(${JSON.stringify(sharpPath)});\n`);
  const { DesktopCaptureArtifacts } = await import(pathToFileURL(compile('main/desktop/captureArtifacts.ts')));
  const { decodeDesktopPng } = await import(pathToFileURL(compile('main/desktop/pngDecoder.ts')));
  let now = 100;
  const dir = path.join(temp, 'captures'), store = new DesktopCaptureArtifacts(dir, decodeDesktopPng, () => now);
  const sharp = createRequire(import.meta.url)('sharp');
  const png = await sharp({ create: { width: 1, height: 1, channels: 4, background: { r: 1, g: 2, b: 3, alpha: 1 } } }).png().toBuffer();
  const capture = await store.create('task', png, 50);
  const mutable = Buffer.from(png), creating = store.create('task', mutable, 40);
  mutable[30] ^= 1;
  const stable = await creating;
  assert.deepEqual(fs.readFileSync(stable.path), png);
  const interrupted = await store.create('task', png, 30); fs.unlinkSync(interrupted.path);
  assert.equal(capture.width, 1); assert.equal(capture.height, 1);
  assert.equal((await store.get('task', capture.artifactId)).path, capture.path);
  assert.deepEqual((await store.readBytes('task', capture.artifactId)).data, png, 'the delivered bytes are the integrity-checked capture');
  await assert.rejects(store.readBytes('other', capture.artifactId), /unavailable/);
  const retract = await store.create('task', png, 40);
  await assert.rejects(store.remove('other', retract.artifactId), /scope/);
  assert.equal(fs.existsSync(retract.path), true);
  await store.remove('task', retract.artifactId);
  assert.equal(fs.existsSync(retract.path), false);
  await assert.rejects(store.get('task', retract.artifactId));
  await assert.rejects(store.get('other', capture.artifactId), /unavailable/);
  await assert.rejects(store.get('task', '../bad'), /identity/);
  await assert.rejects(store.create('task', Buffer.from('not png'), 10), /PNG/);
  const beforeBroken = fs.readdirSync(dir).sort();
  const broken = Buffer.from(png), idat = broken.indexOf(Buffer.from('IDAT'));
  assert.ok(idat > 0); broken[idat + 4] = 0;
  await assert.rejects(store.create('task', broken, 10), /decode PNG/);
  assert.deepEqual(fs.readdirSync(dir).sort(), beforeBroken);
  const mismatched = new DesktopCaptureArtifacts(path.join(temp, 'wrong'), async () => ({ width: 2, height: 1 }), () => now);
  await assert.rejects(mismatched.create('task', png, 10), /dimensions do not match/);
  const tooSlow = new DesktopCaptureArtifacts(path.join(temp, 'slow'), async () => { now += 10; return { width: 1, height: 1 }; }, () => now);
  await assert.rejects(tooSlow.create('task', png, 10), /expired before/);
  assert.equal(fs.existsSync(path.join(temp, 'slow')), false); now -= 10;
  let clockReads = 0;
  const expiresDuringWrite = new DesktopCaptureArtifacts(path.join(temp, 'slow-write'), async () => ({ width: 1, height: 1 }), () => ++clockReads >= 3 ? 110 : 100);
  await assert.rejects(expiresDuringWrite.create('task', png, 10), /expired before/);
  assert.deepEqual(fs.readdirSync(path.join(temp, 'slow-write')), []);
  await assert.rejects(store.create('task', png, 0), /lifetime/);
  const changed = Buffer.from(png); changed[30] ^= 1; fs.writeFileSync(capture.path, changed);
  await assert.rejects(store.get('task', capture.artifactId), /changed/);
  await assert.rejects(store.readBytes('task', capture.artifactId), /changed/);
  fs.writeFileSync(capture.path, png);
  fs.writeFileSync(path.join(dir, 'unrelated.txt'), 'keep');
  const fresh = await store.create('task', png, 100);
  now = 150;
  await assert.rejects(store.get('task', capture.artifactId), /expired/);
  assert.deepEqual(await store.cleanupExpired(), { removed: 3, errors: [] });
  assert.equal(fs.existsSync(capture.path), false);
  assert.equal(fs.existsSync(fresh.path), true);
  assert.equal(fs.readFileSync(path.join(dir, 'unrelated.txt'), 'utf8'), 'keep');
  const metadata = path.join(dir, `${fresh.artifactId}.json`); fs.writeFileSync(metadata, '{');
  now = 1000;
  const failed = await store.cleanupExpired(); assert.equal(failed.removed, 0); assert.equal(failed.errors.length, 1);
  assert.equal(fs.existsSync(fresh.path), true);
  now = Date.now();
  const agedDir = path.join(temp, 'aged'), agedStore = new DesktopCaptureArtifacts(agedDir, decodeDesktopPng, () => now);
  const aged = await agedStore.create('task', png, 100), young = await agedStore.create('task', png, 100);
  const invalidLifetime = await agedStore.create('task', png, 100);
  fs.writeFileSync(path.join(agedDir, `${aged.artifactId}.json`), '{');
  fs.writeFileSync(path.join(agedDir, `${young.artifactId}.json`), '{');
  const badMeta = path.join(agedDir, `${invalidLifetime.artifactId}.json`);
  const value = JSON.parse(fs.readFileSync(badMeta, 'utf8')); value.expiresAt = value.capturedAt + 86400001;
  fs.writeFileSync(badMeta, JSON.stringify(value));
  const orphan = path.join(agedDir, `${randomUUID()}.png`); fs.writeFileSync(orphan, png);
  const youngOrphan = path.join(agedDir, `${randomUUID()}.png`); fs.writeFileSync(youngOrphan, png);
  const unexpectedDirectory = path.join(agedDir, `${randomUUID()}.png`); fs.mkdirSync(unexpectedDirectory);
  const old = new Date(now - 25 * 60 * 60 * 1000);
  for (const file of [aged.path, path.join(agedDir, `${aged.artifactId}.json`), invalidLifetime.path, badMeta, orphan]) fs.utimesSync(file, old, old);
  const reclaimed = await agedStore.cleanupExpired();
  assert.equal(reclaimed.removed, 3); assert.equal(reclaimed.errors.length, 6);
  assert.equal(fs.existsSync(aged.path), false); assert.equal(fs.existsSync(invalidLifetime.path), false);
  assert.equal(fs.existsSync(orphan), false); assert.equal(fs.existsSync(young.path), true, 'young corrupt records remain until the maximum lifetime');
  assert.equal(fs.existsSync(youngOrphan), true); assert.ok(reclaimed.errors.some(error => error.includes('awaits age limit')));
  assert.equal(fs.statSync(unexpectedDirectory).isDirectory(), true, 'cleanup never recursively removes an unexpected directory');
  console.log('desktop captures: task ownership, expiry, integrity and bounded cleanup passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
