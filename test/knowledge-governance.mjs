import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createSharedCompiler} from './helpers/shared-compile.mjs';
fs.mkdirSync('.tmp',{recursive:true});const temp=fs.mkdtempSync(path.resolve('.tmp/knowledge-governance-'));
const compile=createSharedCompiler(process.cwd(),path.join(temp,'compiled'));
const {KnowledgeStore}=await import(pathToFileURL(compile('main/memory/knowledgeStore.ts')));
const store=new KnowledgeStore(path.join(temp,'assets'));
const context=id=>({namespace:'worker',origin:'worker',evidence:[{id,source:'test',eventTime:1,verification:'test'}]});
const lesson={kind:'reusable_lesson',summary:'审批时核对版本',problem:'并发覆盖',action:'提交前比较哈希',rationale:'双窗口测试通过',applicability:['延迟审批'],exceptions:['不可只检查生成时的版本'],expectedFutureUse:'避免旧提案覆盖新内容',repoKey:'E:\\Repo',branch:'main'};
try{
 let old=store.submit(lesson,context('a')).record;old=store.decide(old.id,old.revision,'approve');
 const replacement=store.submit({...lesson,summary:'审批时核对版本与候选状态',action:'提交前比较哈希，并过滤已结算候选'},context('b')).record;
 assert.throws(()=>store.supersede(replacement.id,replacement.revision,old.id,old.revision-1),/变化/);
 const fresh=store.supersede(replacement.id,replacement.revision,old.id,old.revision);
 assert.equal(store.list().records.find(r=>r.id===old.id).status,'superseded');
 assert.equal(fresh.relations[0].targetId,old.id);
 assert.deepEqual(store.search({query:'审批版本',repoKey:'E:/Repo/',branch:'main'}).map(h=>h.record.id),[fresh.id]);
 const revised=store.revise(fresh.id,fresh.revision,{...fresh,action:'用户重新修订的方法',applicability:['特定版本']});
 assert.equal(revised.status,'active');
 const restored=store.restore(revised.id,revised.revision,fresh.revision);
 assert.equal(restored.action,fresh.action);assert.deepEqual(restored.applicability,fresh.applicability);assert.equal(restored.status,fresh.status,'explicit user restore restores the selected version state');
 assert.throws(()=>store.restore(restored.id,revised.revision,fresh.revision),/变化/);
 assert.equal(store.search({query:'审批版本',repoKey:'E:/Repo/',branch:'main'}).length,1);
 const another=store.submit({...lesson,summary:'提交审批时比较版本',action:'比较哈希再提交'},context('c')).record;
 const receipt=store.govern({id:another.id,revision:another.revision,targetId:restored.id,targetRevision:restored.revision,action:'merge',reason:'同一方法的补充依据'});
 let snapshot=store.list();
 assert.equal(snapshot.records.find(r=>r.id===another.id).status,'superseded');
 assert(snapshot.records.find(r=>r.id===restored.id).evidence.some(e=>e.id==='c'));
 store.undoGovernance(another.id,receipt.id);
 snapshot=store.list();
 assert.equal(snapshot.records.find(r=>r.id===another.id).status,'pending');
 assert(!snapshot.records.find(r=>r.id===restored.id).evidence.some(e=>e.id==='c'));
 store.undoGovernance(another.id,receipt.id); // Idempotent inverse.
 const current=snapshot.records.find(r=>r.id===another.id);
 const history=store.govern({id:current.id,revision:current.revision,action:'history',reason:'仅本轮有用'});
 assert.equal(store.list().records.find(r=>r.id===current.id).kind,'task_fact');
 assert.equal(store.submit({...lesson,summary:'提交审批时比较版本',action:'比较哈希再提交'},context('repeat')).disposition,'rejected','history decision suppresses repeated proposal');
 store.undoGovernance(current.id,history.id);
 assert.equal(store.list().records.find(r=>r.id===current.id).kind,'reusable_lesson');
 const boundary=store.submit({...lesson,summary:'其他环境审批',applicability:['不同平台']},context('d')).record;
 const target=store.list().records.find(r=>r.id===restored.id);
 assert.throws(()=>store.govern({id:boundary.id,revision:boundary.revision,targetId:target.id,targetRevision:target.revision,action:'merge',reason:'误合并'}),/条件/);
 assert.equal(store.list().records.find(r=>r.id===boundary.id).revision,1,'rejection changes neither side');
 const distinct=store.govern({id:boundary.id,revision:boundary.revision,targetId:target.id,targetRevision:target.revision,action:'distinct',reason:'平台条件不同'});
 assert.equal(store.list().records.find(r=>r.id===boundary.id).status,'active');
 const changed=store.list().records.find(r=>r.id===target.id);
 store.revise(changed.id,changed.revision,{...changed,summary:'后续用户修订'});
 assert.throws(()=>store.undoGovernance(boundary.id,distinct.id),/后续修改/);
 assert.equal(store.list().records.find(r=>r.id===boundary.id).status,'active','undo conflict is atomic');
 const foreign=store.submit({...lesson,repoKey:'E:/Different'},context('e')).record;
 assert.throws(()=>store.govern({id:foreign.id,revision:foreign.revision,targetId:boundary.id,targetRevision:2,action:'merge',reason:'越界'}),/范围/);
 const currentBoundary=store.list().records.find(r=>r.id===boundary.id);
 const restartUndo=store.govern({id:currentBoundary.id,revision:currentBoundary.revision,action:'history',reason:'跨重启撤销验证'});
 const reopened=new KnowledgeStore(path.join(temp,'assets'));
 assert(reopened.list().governance.some(g=>g.id===receipt.id&&g.undone),'receipts survive restart');
 reopened.undoGovernance(currentBoundary.id,restartUndo.id);
 assert.equal(reopened.list().records.find(r=>r.id===currentBoundary.id).status,'active');
 assert.equal(reopened.list().records.find(r=>r.id===currentBoundary.id).kind,'reusable_lesson');reopened.close();
 const pendingSource=store.list().records.find(r=>r.id===current.id),pendingTarget=store.list().records.find(r=>r.id===restored.id);
 store.govern({id:pendingSource.id,revision:pendingSource.revision,targetId:pendingTarget.id,targetRevision:pendingTarget.revision,action:'merge',reason:'重新合并相同边界'});
 const beforeChange=store.list().records.find(r=>r.id===pendingTarget.id);
 store.revise(beforeChange.id,beforeChange.revision,{...beforeChange,applicability:['新环境']});
 assert.equal(store.submit({...lesson,summary:'提交审批时比较版本',action:'比较哈希再提交'},context('changed-boundary')).disposition,'rejected','a revised merge target cannot silently inherit old boundary evidence');
 console.log('knowledge-governance: atomic replacement, full-content restore, revision conflicts and normalized scope passed');
}finally{store.close();fs.rmSync(temp,{recursive:true,force:true});}
