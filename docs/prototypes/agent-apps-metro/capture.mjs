import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const output = path.join(root,'output/playwright/agent-apps-metro');
await fs.mkdir(output,{recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1060},deviceScaleFactor:1});
const errors = [];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(pathToFileURL(path.join(root,'docs/prototypes/agent-apps-metro/index.html')).href);
  await page.getByRole('heading',{name:'调度的随身应用.'}).waitFor();
  await page.screenshot({path:path.join(output,'01-dark-overview.png'),fullPage:true});
  await page.getByRole('button',{name:/浅色模式/}).click();
  await page.screenshot({path:path.join(output,'02-light-overview.png'),fullPage:true});
  await page.getByRole('button',{name:/深色模式/}).click();
  const messages = page.getByRole('region',{name:'短信应用'});
  await messages.getByRole('button',{name:/林予安/}).click();
  await messages.locator('.detail-page[data-mp-stage="in"]').waitFor();
  await messages.getByRole('textbox',{name:'回复消息'}).fill('下午三点见，我会带上原型。');
  await messages.getByRole('button',{name:'发送演示消息'}).click();
  await messages.getByRole('region',{name:'应用详情'}).getByText('下午三点见，我会带上原型。').waitFor();
  await messages.screenshot({path:path.join(output,'03-message-thread.png'),animations:'disabled'});
  await messages.getByRole('button',{name:'返回列表'}).click();
  const rss=page.getByRole('region',{name:'阅读应用'});
  await rss.getByRole('button',{name:/让工具退后/}).click();
  await rss.getByRole('button',{name:'收藏',exact:true}).click();
  await rss.getByRole('button',{name:'加入待办'}).click();
  await rss.getByRole('status').click();
  await rss.screenshot({path:path.join(output,'04-reader.png'),animations:'disabled'});
  const tasks=page.getByRole('region',{name:'待办应用'});
  await tasks.getByRole('button',{name:'稍后',exact:true}).click();
  assert.equal(await tasks.getByRole('checkbox',{name:'完成阅读：让工具退后，让内容向前。'}).count(),1);
  await page.getByRole('button',{name:'单屏体验'}).click();
  await page.getByRole('navigation',{name:'选择应用'}).getByRole('button',{name:'开始'}).click();
  await page.locator('[data-app="home"][data-active="true"]').waitFor();
  await page.locator('.metro-scene[data-active="true"][data-flight="idle"]').waitFor();
  await page.screenshot({path:path.join(output,'05-launcher.png'),fullPage:true});
  await page.setViewportSize({width:390,height:900});
  await page.getByRole('navigation',{name:'选择应用'}).getByRole('button',{name:'短信'}).click();
  await page.locator('[data-app="messages"][data-active="true"]').waitFor();
  await page.locator('.metro-scene[data-active="true"][data-flight="idle"]').waitFor();
  await page.screenshot({path:path.join(output,'06-narrow.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'viewport horizontal overflow');
  await page.getByRole('button',{name:/浅色模式/}).click();
  await page.screenshot({path:path.join(output,'07-narrow-light.png'),fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  const narrow=page.getByRole('region',{name:'短信应用'});
  await narrow.getByRole('button',{name:/陈默/}).click();
  await narrow.getByRole('button',{name:'返回列表'}).click();
  await narrow.getByRole('button',{name:/陈默/}).waitFor();
  assert.equal(await narrow.locator('.detail-page').count(),0,'reduced motion closes without delayed mount');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,screenshots:7,checks:['reply','article-to-task','launcher','390px overflow','reduced motion','no runtime errors'],output},null,2));
} finally {await browser.close();}
